-- AlterEnum
-- Нейро-ответ поисковика — отдельное значение поверхности.
-- Изменение аддитивное: существующие строки и их тип не трогаются.
-- Откатывается **код, а не схема**: в PostgreSQL нет `ALTER TYPE … DROP VALUE`,
-- и лишнее значение перечисления ничему не мешает — оно просто перестаёт
-- использоваться. Полное удаление потребовало бы пересоздания типа со сменой
-- всех колонок, и ради отката этого делать нельзя.
ALTER TYPE "SearchSurfaceType" ADD VALUE 'AI_ANSWER';
