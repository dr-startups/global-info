"""Report renderer i18n (Stage L2).

Static UI strings for the PPTX/PDF report (section titles, table headers, card
titles, no-data messages, offer-block labels, watermark) in RU / EN. This is the
Python half of the report dictionary; the TypeScript half lives in
``src/modules/digital-profile/report/i18n/report-dictionary.ts``. Code is not
shared — only the key set / wording is kept consistent.

What is NOT translated here (by design):
  - Raw evidence: URLs, source titles, snippets, raw metadata.
  - Enum-like indicators rendered as coloured cells/badges: risk LEVELS
    (LOW/MEDIUM/HIGH/CRITICAL/UNKNOWN), classification and review-status codes.
    These drive the table colour logic and are treated as canonical codes.
The audit-summary / offer prose itself is generated in the report language on
the TypeScript side and arrives already localized in report_json.
"""

