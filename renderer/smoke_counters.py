"""Счётчики проверок для Python-смоков в том виде, в каком их читает раннер.

Раннер (`scripts/run-smokes.ts`) считает выполненные проверки по TAP-строкам
`# tests N` / `# pass N` / `# fail N` и на них же держит правило «прогон без
единой выполненной проверки — провал». Python-смоки этих строк не печатали, и
для раннера их счётчики были `undefined`: смок, не выполнивший **ни одной**
проверки и вышедший с нулём, показывался как «ок».

Это тот самый исход, ради которого раннер и написан, — просто в слепой зоне.
Формат объявлен здесь один раз, чтобы у смоков не появилось по своей копии.
"""

from __future__ import annotations


def print_tap_counters(*, passed: int, failed: int, skipped: int = 0) -> None:
    """Напечатать счётчики так, как их разбирает раннер смоков."""
    print()
    print(f"# tests {passed + failed}")
    print(f"# pass {passed}")
    print(f"# fail {failed}")
    if skipped:
        print(f"# skipped {skipped}")
