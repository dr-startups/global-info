"""Числа, объявленные в TypeScript, — для проверок на стороне рендерера.

Бюджеты знаков и ёмкости страниц живут в `template-registry.ts`; проверяет их
Python. Пока число стояло в проверке литералом, поднятие бюджета на той стороне
оставляло проверку зелёной, а настоящая нагрузка росла — то есть объявленный
предел переставал быть гарантией.

Питон в TS не ходит, поэтому читается исходник. Ненайденное число — отказ, а не
повод считать по умолчанию: «константы нет, значит проверять нечего»
неотличимо от проверки, которой не было.
"""

from __future__ import annotations

import re
from pathlib import Path


def ts_int(path: Path, pattern: str) -> int:
    """Целое по регулярному выражению из исходника; не нашли — отказ."""
    match = re.search(pattern, path.read_text(encoding="utf-8"), re.S)
    if not match:
        raise RuntimeError(f"константа по шаблону {pattern!r} не найдена в {path.name}")
    return int(match.group(1))
