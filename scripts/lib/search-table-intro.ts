/**
 * Что из вводного абзаца реально попадает на лист таблицы выдачи.
 *
 * Зеркало ветки `orion_golden_search_table` в `renderer/orion_golden_render/
 * slides.py`: над таблицей рисуются первые **два полных** предложения, а всё
 * остальное отбрасывается без записи в телеметрию. Именно так на живом прогоне
 * исчезла строка покрытия чтения, стоявшая третьим предложением.
 *
 * Правило продублировано на стороне тестов сознательно — пин обязан мерить тем
 * же, чем мерит лист (прецедент — контракт клиентского текста TS ↔ Python).
 * Копия ровно одна: две расходящиеся копии зелены и врут одновременно.
 *
 * Не зеркалится `_trim_dangling_tail`, который рендерер применяет к уже
 * склеенным двум предложениям: он срезает служебное слово на самом конце, а
 * пины требуют, чтобы интро оканчивалось знаком конца предложения, — на таком
 * входе он тождественен.
 */

/** Разбиение на предложения — то же, что у рендерера. */
const SENTENCE_SPLIT = /(?<=[.!?…])\s+/u;

/** Незакрытая мысль: рендерер такое предложение печатать отказывается. */
const DANGLING_END = /(?:\bкак|\bи|\bс|\bв|\bпо|,|;|—)\s*$/iu;

/** Предложения, которые шаблон `orion_golden_search_table` напечатает. */
export function printedIntroSentences(narrative: string): string[] {
  return narrative
    .split(SENTENCE_SPLIT)
    .map((s) => s.trim())
    .filter((s) => s.length > 0 && /[.!?…]$/u.test(s) && !DANGLING_END.test(s))
    .slice(0, 2);
}
