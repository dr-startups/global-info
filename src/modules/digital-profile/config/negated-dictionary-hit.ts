/**
 * Отрицание рядом со словом снимает совпадение — один предикат на все словари.
 *
 * На финальном прогоне шага 15 в отчёт попало:
 *
 *     «Финансовые претензии / долговые споры»
 *     «По компаниям, которыми руководит или руководил ДУРОВ ПАВЕЛ ВАЛЕРЬЕВИЧ
 *      **не было выставленных претензий** от партнёров и клиентов на 07.07.2026.»
 *
 * Материал утверждает **отсутствие** претензий, а отчёт завёл по нему тему
 * риска: словарь поймал слово «претензий» и не заметил отрицания.
 *
 * **Окно в обе стороны.** Первая редакция смотрела только назад — снимала
 * совпадение, если отрицание стояло перед словом. По-русски опровержение чаще
 * стоит **после** предмета: «обвинения не подтвердились», «претензии сняты»,
 * «дело прекращено», — и в этом порядке защиты не было вовсе.
 *
 * **Почему окно, а не «есть ли в тексте опровержение вообще».** Список без окна
 * отвечает на другой вопрос. На заголовке «Суд отказал в иске, но обвинения в
 * избиении остаются» он снял бы всё; окно оставляет «избиение», потому что до
 * него опровержение не дотягивается, и такой заголовок остаётся негативом. До
 * пополнения словаря словами обвинения это было свойством предиката, а не
 * ответом отчёта: «обвин» и «избие» словарь не знал, единственным совпадением
 * оставался «суд» вплотную к «отказал», и метку заголовок терял.
 * Ширина окна — одно число на обе стороны:
 * не больше трёх слов между оборотом и словом. Прежняя редакция считала иначе —
 * окно росло вместе с длиной оборота, — то есть у одного вопроса было два
 * ответа; цена единого числа названа ниже.
 *
 * **Списка опровержений здесь нет — он в конфиге** (`denialPatterns` в
 * `finding-themes.ts`), и читает его не только этот предикат: по нему же
 * `detectContradictions` находит источники, спорящие по существу. Второй список
 * был бы вторым ответом на вопрос «что такое опровержение», и они разошлись бы,
 * как расходились два словаря негатива.
 *
 * **Чего конструкция не ловит — названо, чтобы её не приняли за понимание
 * смысла:**
 *
 * - опровержение в другом предложении: окно считается по словам одной строки,
 *   а строка склеена из заголовка и сниппета;
 * - пересказ: «обвинения рассыпались в суде» — ни одного слова из списков;
 * - структурное отрицание: в оборотах есть «не было», но нет «не был», и
 *   «никто не был обвинён» совпадение сохраняет;
 * - отрицание дальше трёх слов: «Не было никаких оснований для возбуждения
 *   уголовного дела» метку **сохранит** — между «было» и «уголовного» четыре
 *   слова;
 * - многословную альтернативу словаря («watch.?list», «national security»,
 *   «арбитражн\w* иск»): вхождения считаются пословно, такое совпадение в счёт
 *   не попадает вовсе и снятым не бывает ни при каком окружении. Направление
 *   безопасное — метка остаётся, — но «каждое вхождение» ниже читать надо
 *   именно так.
 *
 * **И чем она платит — это целый класс, а не один пример.** Оборот стоит рядом,
 * но относится к другому предмету, и предикат этого не видит:
 *
 * - «Суд отказал в удовлетворении иска о защите чести» — материал судебный;
 * - «Банк отказал в кредите после ареста счетов» — отказ не про обвинение;
 * - «Видео снято при обыске в офисе» — снято видео, а не обвинения;
 * - «Ограничения сняты, расследование продолжается» — источник прямо говорит,
 *   что негативное продолжается, но запятая границей не считается (см.
 *   `CLAUSE_BREAKS`).
 *
 * Цена принята сознательно. Отчёт читает сам субъект, и ошибки здесь
 * несимметричны: снятая метка делает строку «Не проверено» — читатель видит
 * заголовок и слова о том, что мы это не проверяли, а оператор может пометить
 * строку вручную. Ложный «Нежелательный» на опровержении, наоборот, предлагает
 * клиенту убирать материал, который его оправдывает.
 */

import { resolveFindingThemesConfig } from "./finding-themes";

/**
 * Обороты, отрицающие факт рядом с собой.
 *
 * Голых кванторов («нет», «без», «no», «not», «none», «without») здесь нет
 * намеренно, хотя раньше они в списке стояли. Пока окно смотрело только вперёд,
 * они отрицали то, что идёт следом; с окном в обе стороны они стали снимать
 * соседнее слово словаря, ничего о нём не утверждая: «Уголовное дело:
 * комментариев нет», «Обыск в офисе прошёл без понятых», «Sanctions review: no
 * comment» — все три метку теряли, причём последняя описывает нарушение.
 * Вернуть их «только вперёд» нельзя: по-русски «претензий нет» и «нет
 * претензий» — одно и то же, и направление снова решал бы порядок слов. Цена
 * названа и шире одной фразы: совпадения больше не снимает любая конструкция
 * «без …» и «нет …» перед словом — «Нет претензий», «Без претензий по договору»,
 * «Без уголовного преследования». На строке выдачи это не регресс (предикат там
 * прежде не спрашивался), на теме материала — регресс.
 */
const NEGATIONS = [
  "не было",
  "не выставлено",
  "не выставлены",
  "не выставленных",
  "не выявлено",
  "не выявлены",
  "не зафиксировано",
  "не зафиксированы",
  "не обнаружено",
  "не обнаружены",
  "не найдено",
  "не найдены",
  "не имеется",
  "не имелось",
  "не заявлено",
  "не заявлены",
  "не установлено",
  "не установлены",
  "отсутствуют",
  "отсутствует",
  "отсутствовали",
];

/**
 * Сколько слов между оборотом и словом словаря ещё считается «рядом».
 *
 * Три слова покрывают «не было выставленных претензий» и «обвинения в избиении
 * не подтвердились», но не дотягиваются до другого предложения. Число одно на
 * обе стороны окна: «рядом» слева и справа — один вопрос.
 */
const MAX_WORDS_BETWEEN = 3;

/** Отрезок слов, занятый оборотом. */
type Span = { first: number; last: number };

/**
 * Слова, на которых окно кончается.
 *
 * Противительный союз и точка с запятой — заявление источника о том, что
 * негативное продолжается: «санкции сняты, **но** расследование продолжается»,
 * «претензий не было, **но** долг взыскан в суде». Оборот из первой части ко
 * второй отношения не имеет, и окно через такую границу не ходит.
 *
 * Запятой в списке нет намеренно: по-русски она отделяет и причастный оборот,
 * и «Обвинения, выдвинутые прокуратурой, не подтвердились» осталось бы
 * отмеченным — ровно та ошибка, ради которой предикат и написан.
 */
const CLAUSE_BREAKS = new Set(["но", "однако", ";"]);

function normalize(text: string): string {
  return String(text ?? "")
    .toLowerCase()
    .replace(/ё/gu, "е")
    // Точка с запятой доживает до разметки отдельным словом: она граница, а не
    // пунктуация, которую можно стереть вместе с остальными знаками.
    .replace(/;/gu, " ; ")
    .replace(/[^\p{L}\p{N};\s]/gu, " ")
    .replace(/\s+/gu, " ")
    .trim();
}

function negationSpans(words: string[]): Span[] {
  const spans: Span[] = [];
  for (let i = 0; i < words.length; i += 1) {
    for (const neg of NEGATIONS) {
      const parts = neg.split(" ");
      if (parts.every((p, k) => words[i + k] === p)) {
        spans.push({ first: i, last: i + parts.length - 1 });
      }
    }
  }
  return spans;
}

/**
 * Опровержения из конфига — с переводом позиции в строке в номера слов.
 *
 * Выражение конфига многословное («не подтвердил», «снял обвинени»), поэтому
 * пословно его не проверить: ищем по склеенной строке и отмечаем, какие слова
 * оборот занял.
 */
function denialSpans(words: string[]): Span[] {
  const denial = resolveFindingThemesConfig().denialPatterns;
  const probe = new RegExp(
    denial.source,
    denial.flags.includes("g") ? denial.flags : `${denial.flags}g`
  );
  const line = words.join(" ");
  const wordAt: number[] = [];
  words.forEach((word, index) => {
    for (let k = 0; k <= word.length; k += 1) wordAt.push(index);
  });
  const spans: Span[] = [];
  for (const match of line.matchAll(probe)) {
    const from = match.index ?? 0;
    const to = from + Math.max(match[0].length, 1) - 1;
    spans.push({ first: wordAt[from] ?? 0, last: wordAt[to] ?? words.length - 1 });
  }
  return spans;
}

/**
 * Отрицается ли совпадение словаря в этом тексте.
 *
 * `true` означает: слово словаря в тексте есть, но **каждое** его вхождение
 * стоит рядом с отрицанием или опровержением — то есть источник говорит об
 * отсутствии, а не о наличии. Хоть одно вхождение без оборота рядом — и
 * совпадение остаётся: «Суд отказал в иске, но обвинения в избиении остаются».
 *
 * Словарь уже совпал у того, кто спрашивает (иначе спрашивать было бы не о
 * чем), поэтому второй раз по исходному тексту он здесь не проверяется.
 */
export function dictionaryHitIsNegated(text: string, dictionary: RegExp): boolean {
  const raw = String(text ?? "");
  if (!raw.trim()) return false;

  const words = normalize(raw).split(" ");
  const spans = [...negationSpans(words), ...denialSpans(words)];
  if (spans.length === 0) return false;

  const breaks = words.flatMap((word, i) => (CLAUSE_BREAKS.has(word) ? [i] : []));
  const crossesBreak = (from: number, to: number) =>
    breaks.some((b) => b > Math.min(from, to) && b < Math.max(from, to));

  // Слово, попавшее внутрь самого оборота, снято вместе с ним: «снял
  // обвинения» несёт слово словаря в себе.
  const cleared = (i: number) =>
    spans.some((s) => {
      if (i >= s.first && i <= s.last) return true;
      if (i > s.last) return i - s.last <= MAX_WORDS_BETWEEN + 1 && !crossesBreak(s.last, i);
      return s.first - i <= MAX_WORDS_BETWEEN + 1 && !crossesBreak(i, s.first);
    });

  const word = new RegExp(dictionary.source, dictionary.flags.replace("g", ""));
  let seen = 0;
  for (let i = 0; i < words.length; i += 1) {
    if (!word.test(words[i]!)) continue;
    seen += 1;
    if (!cleared(i)) return false;
  }
  return seen > 0;
}
