/**
 * Отрицание перед словом темы — не признак темы (шаг 15, J1).
 *
 * На финальном прогоне в отчёт попало:
 *
 *     «Финансовые претензии / долговые споры»
 *     «По компаниям, которыми руководит или руководил ДУРОВ ПАВЕЛ ВАЛЕРЬЕВИЧ
 *      **не было выставленных претензий** от партнёров и клиентов на 07.07.2026.»
 *     Банки и инвесторы обычно запрашивают статус обязательств.
 *
 * Материал утверждает **отсутствие** претензий, а отчёт завёл по нему тему
 * риска: тематизатор поймал слово «претензий» и не заметил отрицания.
 *
 * Это опаснее прежних текстовых дефектов. Косноязычие читатель простит;
 * утверждение, противоположное источнику, он покажет банку.
 *
 * Правило намеренно узкое. Отрицание должно стоять непосредственно перед
 * словом темы: «дело не закрыто» и «не смог оспорить претензии» — это по-
 * прежнему тема, потому что отрицание там относится к другому. Ошибка в
 * сторону «оставить тему» безопаснее: пропущенный риск виден аналитику,
 * выдуманный — нет.
 */

/** Обороты, отрицающие то, что стоит следом. */
const NEGATIONS = [
  "не было",
  "не выставлено",
  "не выставлены",
  "не выставленных",
  "не выявлено",
  "не выявлены",
  "не зафиксировано",
  "не зафиксированы",
  "не обнаружено",
  "не обнаружены",
  "не найдено",
  "не найдены",
  "не имеется",
  "не имелось",
  "не заявлено",
  "не заявлены",
  "не установлено",
  "не установлены",
  "отсутствуют",
  "отсутствует",
  "отсутствовали",
  "нет",
  "без",
  "no",
  "not",
  "without",
  "none",
];

/**
 * Сколько слов между отрицанием и словом темы ещё считается «непосредственно».
 *
 * Три слова покрывают «не было выставленных претензий» и «не выявлено
 * признаков банкротства», но не дотягиваются до другого предложения.
 */
const MAX_WORDS_BETWEEN = 3;

function normalize(text: string): string {
  return String(text ?? "")
    .toLowerCase()
    .replace(/ё/gu, "е")
    .replace(/[^\p{L}\p{N}\s]/gu, " ")
    .replace(/\s+/gu, " ")
    .trim();
}

/**
 * Отрицается ли совпадение темы в этом тексте.
 *
 * `true` означает: слово темы в тексте есть, но перед **каждым** его вхождением
 * стоит отрицание — то есть источник говорит об отсутствии, а не о наличии.
 * Если хоть одно вхождение не отрицается, тема остаётся.
 */
export function themeHitIsNegated(text: string, keywords: RegExp): boolean {
  const raw = String(text ?? "");
  if (!raw.trim()) return false;

  // Проверяем по исходному тексту, чтобы не сломать словарь темы нормализацией,
  // а окно отрицания считаем по словам нормализованного.
  const probe = new RegExp(keywords.source, keywords.flags.includes("g") ? keywords.flags : `${keywords.flags}g`);
  const matches = [...raw.matchAll(probe)];
  if (matches.length === 0) return false;

  const words = normalize(raw).split(" ");
  const negatedAt = new Set<number>();
  for (let i = 0; i < words.length; i += 1) {
    for (const neg of NEGATIONS) {
      const parts = neg.split(" ");
      if (parts.every((p, k) => words[i + k] === p)) {
        for (let d = 1; d <= MAX_WORDS_BETWEEN + parts.length; d += 1) {
          negatedAt.add(i + parts.length - 1 + d);
        }
      }
    }
  }
  if (negatedAt.size === 0) return false;

  // Каждое вхождение слова темы обязано попадать в окно отрицания.
  const normalizedProbe = new RegExp(
    keywords.source,
    keywords.flags.includes("g") ? keywords.flags : `${keywords.flags}g`
  );
  let index = 0;
  let seen = 0;
  for (let i = 0; i < words.length; i += 1) {
    normalizedProbe.lastIndex = 0;
    if (!normalizedProbe.test(words[i]!)) continue;
    seen += 1;
    if (!negatedAt.has(i)) return false;
    index = i;
  }
  void index;
  return seen > 0;
}
