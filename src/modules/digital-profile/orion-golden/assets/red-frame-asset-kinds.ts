/**
 * Рисует ли ассет этого вида красные рамки — один ответ на весь продукт.
 *
 * Отдельным файлом, а не в соседях, по двум измеренным причинам. У рисующих
 * (`media-asset-svg.ts`) первой строкой `import sharp`, и валидатор деки,
 * спрашивающий ответ, потащил бы нативную библиотеку в свой граф: падение её
 * биндинга уносило бы с собой всю проверку деки. А `canonical-slots.ts`, где
 * поле `kind` объявлено, входит в отпечаток построителей, и правка этого
 * ответа требовала бы подъёма `DECK_CONTENT_VERSION` — то есть перерасчёта
 * готовых пакетов ради строки, которая ни одной собранной деки не касается.
 * Лежит рядом с рисующими: смотреть надо туда же, куда и за самой рамкой.
 */

/**
 * Рисует ли ассет этого вида красные рамки на строках.
 *
 * Один ответ на вопрос «есть ли на этой картинке рамки». Он нужен потому, что
 * `visibleItems` заполняет один классификатор у **всех** видов, и `adverse`
 * там значит «формулировка негативная», а не «строка обведена». Обводит
 * рисующий: `renderSerpSnapshotPng` — блок результата на снимке выдачи,
 * `buildSurfacePanelSvg` — строку панели, `buildImageGridSvg` — плитку сетки.
 * `buildKnowledgePanelSvg` получает только заголовок, сводку и факты и не
 * рисует ни одной рамки, а настоящий скриншот (`live_serp`) мы не рисуем
 * вовсе — байты приходят с контура захвата.
 *
 * Спрашивает ворот «каждая нарисованная рамка объяснена»: без этого ответа он
 * считал рамкой негативную строку панели знаний и требовал под ней фразу
 * «почему выделено», которой там неоткуда взяться.
 *
 * `null` — «вид неизвестен», и спрашивающий обязан объявить незнание словами.
 * Молчаливое «рамок нет» ослепляет ворот на новой поверхности, молчаливое
 * «рамки есть» даёт ложный отказ; выдумывать ответ за того, кто добавил вид,
 * нельзя ни в ту, ни в другую сторону.
 */
export function assetKindDrawsRedFrames(kind: string): boolean | null {
  switch (kind) {
    case "serp_screenshot":
    case "surface_panel":
    case "image_grid":
      return true;
    case "live_serp":
    case "knowledge_panel":
      return false;
    /*
     * Словарь замороженной фикстуры эталона 72 — он старше нынешнего.
     *
     * `report-assets.fixture.json` — метаданные канареечного прогона, и виды
     * там свои: `serp_snapshot` вместо `serp_screenshot`, а `visual` покрывает
     * сразу панели подсказок и связанных запросов (рамки рисуют) и панель
     * знаний (не рисует). Ответ «рисует» выбран сознательно: ошибка в эту
     * сторону громкая (ворот заговорит, и на строку посмотрят), ошибка в
     * обратную — молчаливая слепота приёмки. Замерено: негативных строк у
     * панелей знаний эталона нет ни одной, поэтому сегодня различие не видно.
     */
    case "serp_snapshot":
    case "visual":
      return true;
    default:
      return null;
  }
}
