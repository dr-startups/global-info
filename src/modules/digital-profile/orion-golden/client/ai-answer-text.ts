/**
 * Ответ поискового ИИ — клиентским текстом, без разметки.
 *
 * Нейро-ответ Яндекса приходит размеченным Markdown, и на живом прогоне 20.08
 * это доехало до бумаги дословно: `**Михаил Дмитриевич Прохоров**` со
 * звёздочками, строки со звёздочкой-маркером списка и сноски `[1][4]`.
 * Владелец прочитал страницу как «в целом каша».
 *
 * Хуже разметки было её следствие: страница печатает ответ, разложенный по
 * границам предложений (`packSentencesNoTruncate`), а в размеченном тексте
 * после точки идёт `\n\n**Заголовок**` и сноска. Разбивка приходилась **между**
 * предложением и его сноской, и следующий буллет начинался с «[2]».
 *
 * Снимаются только знаки разметки: слова ответа не трогаются. **Сырое
 * наблюдение тоже не трогается** — в `snippet` ответ остаётся дословным,
 * прослеживаемость до первоисточника важнее удобства печати.
 *
 * Модуль живёт в слое клиентского текста, потому что его зовут оба пути:
 * построитель страницы и сборка картинки-панели. Один вопрос — один ответ.
 */

/**
 * Сноски вида `[1]`, `[2][3]`.
 *
 * Они ссылаются на нумерованный список источников Яндекса, которого в отчёте
 * нет: у нас источники печатаются своими строками «Источник: … — домен» и в
 * другом порядке. Номер, ведущий в никуда, — то же самое, что машинный код.
 */
const FOOTNOTES = /\s*\[\d+\](?:\s*\[\d+\])*/gu;

/** Маркер списка в начале строки: `*`, `-`, `•`, а также заголовок `#`. */
const LINE_MARKER = /^\s*(?:[*\-•]\s+|#{1,6}\s+)/u;

/** Кончается ли строка так, что следующая к ней не приклеится. */
const ENDS_SENTENCE = /[.!?…:»)]$/u;

export function plainAiAnswerText(raw: string | null | undefined): string {
  const lines = String(raw ?? "")
    .replace(/\r\n/gu, "\n")
    .replace(FOOTNOTES, "")
    // Парный жирный — в первую очередь: иначе одиночная чистка ниже разорвёт
    // пару и оставит половину знаков.
    .replace(/\*\*([^*]+)\*\*/gu, "$1")
    .replace(/__([^_]+)__/gu, "$1")
    .split("\n")
    .map((line) => line.replace(LINE_MARKER, "").trim())
    // Оставшиеся одиночные звёздочки — курсив Markdown. Других причин для
    // звёздочки в ответе поисковика нет, а `**` в отчёте банку — дефект.
    .map((line) => line.replace(/\*/gu, "").replace(/\s+/gu, " ").trim())
    .filter(Boolean)
    /*
     * Каждая строка — законченная мысль.
     *
     * Пункт списка приходит без точки, и без неё следующий приклеивается к
     * предыдущему: разбивка по предложениям снова разъезжается, а буллет
     * начинается с середины фразы. Заголовок с двоеточием точки не получает —
     * двоеточие уже кончает строку.
     */
    .map((line) => (ENDS_SENTENCE.test(line) ? line : `${line}.`));
  return lines.join(" ").trim();
}
