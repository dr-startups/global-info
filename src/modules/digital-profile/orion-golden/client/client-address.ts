/**
 * Адрес источника так, как его читает клиент, — **один ответ на весь отчёт**.
 *
 * Разбор адреса лежал в `deck-sections/fragment-builders/shared.ts`, куда
 * аналитике ходить нельзя, и поэтому аналитика печатала домен: «„Прохоров
 * Михаил Дмитриевич Москва“ — источник bizfiles.org». Владелец на отчёте 20.08
 * прочитал это как «где-то на сайте есть, ищите сами» и назвал общее правило:
 * источник даётся полной ссылкой.
 *
 * Модуль живёт в слое клиентского текста рядом с `risk-scale.ts` — оттуда его
 * видят оба потребителя, и второй копии правила в проекте нет.
 */

import { clientSafeDomain } from "../../services/composite-serp-merge";

/** Хост и путь адреса — разбор без политики печати. */
export function parseClientAddress(
  url: string | undefined
): { host: string; path: string } | undefined {
  const raw = String(url ?? "").trim();
  if (!raw) return undefined;
  // Только публичные схемы: `arsenkin://suggestion/17` адресом не является, и
  // `new URL` честно отдал бы для него хост «suggestion».
  if (!/^https?:\/\//iu.test(raw)) return undefined;
  let parsed: URL;
  try {
    parsed = new URL(raw);
  } catch {
    return undefined;
  }
  let path = parsed.pathname.replace(/\/$/u, "");
  try {
    path = decodeURIComponent(path);
  } catch {
    // Битая процентная последовательность — печатаем путь как есть.
  }
  /*
   * Строка параметров и якорь остаются частью адреса.
   *
   * Без них `youtube.com/watch?v=…` превращается в `youtube.com/watch` —
   * ссылку, которая открывает пустой проигрыватель. Метки отслеживания
   * (`utm_*`, `fbclid`) при этом не вычищаются: адрес, который открывается,
   * дороже короткого, а решать, какой параметр адресует страницу, а какой нет,
   * значит гадать.
   */
  return { host: parsed.hostname.replace(/^www\./u, ""), path: `${path}${parsed.search}${parsed.hash}` };
}

/**
 * Адрес для клиента: читаемый хост и весь путь, без протокола.
 *
 * `undefined` — назвать нечего: пустой или неразбираемый адрес, либо хост из
 * демонстрационных данных. Имя демо-домена не должно оказаться в отчёте, и
 * прочерк вместо адреса тоже не годится — это сломанный текст.
 *
 * Протокол не печатается намеренно: в тексте он ничего не добавляет — адрес
 * копируется в браузер и без него, — а восемь знаков ширины отнимает.
 *
 * Кириллическая зона печатается кириллицей: в отчёте 28.07 клиент читал
 * `xn--h1ajim.xn--p1ai`. Формально верно, но документ показывают человеку.
 */
export function clientAddress(url: string | undefined): string | undefined {
  const parts = parseClientAddress(url);
  if (!parts) return undefined;
  const host = clientSafeDomain(parts.host);
  return host ? `${host}${parts.path}` : undefined;
}

/**
 * Адрес внутри предложения — в круглых скобках.
 *
 * Скобки решают спор о точке: `lenta.ru/tags/persons/prohorov-mihail.` не
 * читается — то ли точка часть адреса, то ли конец предложения. Закрывающая
 * скобка кончает адрес, а знак препинания стоит снаружи.
 */
export function clientAddressText(url: string | undefined): string | undefined {
  const address = clientAddress(url);
  return address ? `(${address})` : undefined;
}

/**
 * Хвост «— источник …» для строки с цитатой или заголовком.
 *
 * Адрес известен — называется он; известен только домен — называется домен:
 * это по-прежнему прослеживаемость, просто более грубая. Не известно ничего —
 * пустая строка: источник, которого нет, не выдумывается и прочерком не
 * обозначается.
 */
export function sourceAttribution(input: {
  url?: string | undefined;
  domain?: string | undefined;
}): string {
  const address = clientAddressText(input.url);
  if (address) return ` — источник ${address}`;
  const domain = clientSafeDomain(input.domain);
  return domain ? ` — источник ${domain}` : "";
}

/**
 * Хвост «— источник …» в уже собранном тексте.
 *
 * Нужен проверкам, которые ищут строки-цитаты в готовом черновике: перекладке
 * тематического буллета и сторожу, следящему, что модель не потеряла источник.
 * Обе искали `источник <домен>` и на форме `источник (адрес)` переставали
 * видеть строку вовсе — а форма сменилась ровно тогда, когда источник стали
 * называть полным адресом.
 *
 * Группой захватывается **площадка**, а не весь адрес: сверки идут по домену,
 * и адрес с параметрами сравнивать с адресом без них незачем. Совпадение при
 * этом покрывает адрес целиком, вместе с путём и закрывающей скобкой: строка,
 * опознанная наполовину, при перекладке буллета рвалась пополам — путь
 * отрывался от своей цитаты и уезжал в конец абзаца.
 */
export const SOURCE_ATTRIBUTION_SOURCE = String.raw`—\s*источник\s+\(?([A-Za-z0-9][A-Za-z0-9.-]*)(?:[^\s)]*\))?`;

