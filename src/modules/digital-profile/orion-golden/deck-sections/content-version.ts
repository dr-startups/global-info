/**
 * Номер версии, при котором снят отпечаток выше.
 *
 * Номер входит в сам хэш (`sha256(соль + имена и содержимое файлов)`, солью
 * служит он), и это не украшение, а весь механизм. Пока отпечаток снимался с
 * одних исходников, посчитанное по ним значение годилось при **любом** номере:
 * правишь построитель, вставляешь один отпечаток — и сторож зелен при
 * неподвижном `DECK_CONTENT_VERSION`, то есть правка молча приезжает из кэша
 * прежней. Замерено мутацией 29.08 на `e7071aa`: комментарий в
 * `fragment-builders/appendix.ts` плюс новый отпечаток давали четырнадцать
 * зелёных тестов.
 *
 * Что сторож умеет и чего не умеет — в доктексте `content-version-guard.ts`,
 * где живёт само правило. Коротко: подсказка называет отпечаток для поднятого
 * номера; отпечаток при действующем номере она называет только объявленному
 * исключению и снимает его **под причину исключения**. От того, кто посчитает
 * sha256 сам, сторож не защищает и защищать не может — истории у него нет.
 *
 * Значение отпечатка сменилось на v144 без подъёма номера ровно по этой
 * причине: изменилась формула, а не исходники построителей.
 */
export const FINGERPRINT_TAKEN_AT_VERSION = "deck-sections-v154" as const;

/** Объявленное исключение из правила «отпечаток сдвинулся — сдвинулся и номер». */
export type FingerprintVersionException = {
  /**
   * Отпечаток, ради которого исключение объявлено; он же записан в
   * `DECK_BUILDER_FINGERPRINT`. Это не второй ответ на тот же вопрос, а
   * привязка: со следующей правкой построителей значения разойдутся, и
   * исключение перестанет действовать само. Без привязки оставленное в дереве
   * исключение прикрыло бы чужую правку и превратило сторож в выключатель.
   *
   * Объявляя исключение, поле оставляют **пустым**: только в этом состоянии
   * сторож называет отпечаток. Устаревшему исключению он не называет ничего.
   */
  readonly fingerprint: string;
  /**
   * Почему правка заведомо не может изменить ни одну собранную деку. Пустая
   * причина исключением не считается: голый флаг неотличим от забывчивости, а
   * причина попадает в дифф и читается в ревью.
   *
   * Причина входит в соль отпечатка, поэтому она не подпись, а часть ключа:
   * перепишете причину — записанный отпечаток перестанет годиться.
   */
  readonly reason: string;
};

