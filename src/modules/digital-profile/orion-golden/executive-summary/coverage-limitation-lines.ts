/**
 * Ограничение покрытия клиентскими словами — **один ответ на весь отчёт**.
 *
 * Строка называет направление и причину: «поверхность не собрана в текущем
 * прогоне» без имени направления — половина обещания правила «пустое состояние
 * честнее выдуманного», и стр. 4 живого отчёта 91 читалась именно так.
 *
 * Сводятся строки по причине, а не по направлению: четыре пробела с одной
 * причиной давали в резюме одну и ту же фразу трижды подряд — ровно то, ради
 * чего имя когда-то и сняли. Порядок — порядок пробелов: резюме обязано быть
 * детерминированным.
 *
 * Модуль листовой и лежит рядом с самими пробелами (`dataGaps` — поле входа
 * резюме), потому что читателей у правила двое и в разных слоях: сводка
 * резюме (`deterministic-composer`) и клиентский пакет (`run-analytics-pipeline`).
 * Две почти одинаковые склейки разошлись бы молча — это и есть форма дефекта,
 * ради которой в проекте заведено «один вопрос — один ответ».
 */

/**
 * Разделитель направления и причины — тире, а не двоеточие.
 *
 * Строка печатается после «Ограничения покрытия: », и второе двоеточие подряд
 * («Ограничения покрытия: проверка URL и индексации: поверхность не собрана»)
 * читается спотыкаясь.
 */
const AREA_DETAIL_SEPARATOR = " — ";

export function clientCoverageLimitationLines(
  gaps: ReadonlyArray<{ area: string; detail: string }>
): string[] {
  const areasByDetail = new Map<string, string[]>();
  for (const gap of gaps) {
    const areas = areasByDetail.get(gap.detail) ?? [];
    if (!areas.includes(gap.area)) areas.push(gap.area);
    areasByDetail.set(gap.detail, areas);
  }
  return [...areasByDetail].map(
    ([detail, areas]) => `${areas.join(", ")}${AREA_DETAIL_SEPARATOR}${detail}`
  );
}
