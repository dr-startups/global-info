/**
 * Кириллица → латиница одной таблицей.
 *
 * Таблица общая по необходимости, а не для порядка: этой функцией профиль
 * субъекта порождает свои транслитерации, и ею же классификатор сверяет с ними
 * латинские написания из выдачи. Разойдись две копии в одной букве —
 * собственное отчество субъекта перестанет совпадать со своей же
 * транслитерацией и будет объявлено чужим.
 */
const RU_TO_LAT: Record<string, string> = {
  а: "a",
  б: "b",
  в: "v",
  г: "g",
  д: "d",
  е: "e",
  ё: "e",
  ж: "zh",
  з: "z",
  и: "i",
  й: "y",
  к: "k",
  л: "l",
  м: "m",
  н: "n",
  о: "o",
  п: "p",
  р: "r",
  с: "s",
  т: "t",
  у: "u",
  ф: "f",
  х: "kh",
  ц: "ts",
  ч: "ch",
  ш: "sh",
  щ: "shch",
  ъ: "",
  ы: "y",
  ь: "",
  э: "e",
  ю: "yu",
  я: "ya",
};

export function transliterateRuToLat(input: string): string {
  return input
    .toLowerCase()
    .split("")
    .map((ch) => RU_TO_LAT[ch] ?? ch)
    .join("");
}
