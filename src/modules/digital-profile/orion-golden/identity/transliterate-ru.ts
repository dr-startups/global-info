/**
 * Кириллица → латиница одной таблицей.
 *
 * Таблица общая по необходимости, а не для порядка: этой функцией профиль
 * субъекта порождает свои транслитерации, ею же классификатор выводит латинские
 * формы фамилии и сверяет с ними написания из выдачи. Разойдись две копии в
 * одной букве — собственная фамилия субъекта перестанет совпадать со своей же
 * транслитерацией и уедет в кандидаты в имена, а собственное отчество будет
 * объявлено чужим.
 *
 * Школа здесь одна из двух: `transliterateRuToEn` планировщика запросов пишет
 * «ё» как «yo» (Кремлёв → Kremlyov), и в материалах встречаются оба написания.
 * Поэтому формы фамилии классификатор выводит обеими таблицами — но порождает
 * `transliterations` профиля по-прежнему только эта, иначе разошлись бы уже
 * сами транслитерации.
 */
const RU_TO_LAT: Record<string, string> = {
  а: "a",
  б: "b",
  в: "v",
  г: "g",
  д: "d",
  е: "e",
  ё: "e",
  ж: "zh",
  з: "z",
  и: "i",
  й: "y",
  к: "k",
  л: "l",
  м: "m",
  н: "n",
  о: "o",
  п: "p",
  р: "r",
  с: "s",
  т: "t",
  у: "u",
  ф: "f",
  х: "kh",
  ц: "ts",
  ч: "ch",
  ш: "sh",
  щ: "shch",
  ъ: "",
  ы: "y",
  ь: "",
  э: "e",
  ю: "yu",
  я: "ya",
};

export function transliterateRuToLat(input: string): string {
  return input
    .toLowerCase()
    .split("")
    .map((ch) => RU_TO_LAT[ch] ?? ch)
    .join("");
}
