/**
 * Глубина выдачи на один запрос.
 *
 * Правило одно и записано здесь один раз: **настройка провайдера — это глубина
 * по умолчанию, а не потолок**. Потолок задаёт только сам API.
 *
 * Появилось после разбора живого прогона: аудит просил ТОП-20, а оба провайдера
 * считали глубину как `Math.min(запрошено ?? настройка, настройка)` — то есть
 * молча срезали запрошенное до своего значения по умолчанию (10). Отчёт при
 * этом продолжал называть себя аудитом ТОП-20 и показывал первую страницу
 * выдачи. Ошибка не была видна ни в логах, ни в предупреждениях: провайдер
 * честно возвращал `SUCCESS`, просто вдвое короче.
 */
export function resolveSearchDepth(input: {
  /** Сколько просит вызывающий; `undefined` — «не важно, дай по умолчанию». */
  requested?: number;
  /** Глубина по умолчанию из настроек провайдера. */
  fallback: number;
  /** Предел, дальше которого API не имеет смысла просить. */
  max: number;
}): number {
  const wanted = Number.isFinite(input.requested) && (input.requested as number) > 0
    ? Math.trunc(input.requested as number)
    : Math.trunc(input.fallback);
  const safeMax = Math.max(1, Math.trunc(input.max));
  return Math.max(1, Math.min(wanted, safeMax));
}
