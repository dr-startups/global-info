/**
 * Согласование существительного с числом в русском тексте отчёта.
 *
 * Отдельный файл, потому что правило нужно и аналитике (материалы, страницы,
 * публикации), и разбору ответа комплаенс-провайдера, а он объявлен модулем
 * чистых функций и тянуть в него синтезатор находок незачем. Второй копии
 * правила в проекте быть не должно: расходятся именно такие копии.
 */

/** 1 публикация, 2 публикации, 5 публикаций. */
export function pluralRu(n: number, one: string, few: string, many: string): string {
  const abs = Math.abs(n) % 100;
  const last = abs % 10;
  if (abs > 10 && abs < 20) return many;
  if (last === 1) return one;
  if (last >= 2 && last <= 4) return few;
  return many;
}
