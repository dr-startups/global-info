/**
 * Одна ли это строка выдачи — один ответ на весь продукт.
 *
 * Ключ наблюдения включает запрос (`serp-observation/persist.ts`), и это
 * намеренно: одна и та же страница, найденная двумя запросами, — два
 * наблюдения, и оба нужны провенансу. Читателю она при этом одна, поэтому
 * строки сводит по материалу тот, кто **выбирает их для показа**: отбор строк
 * колонки снимка (`selectVisibleObservationsForEngine`), список видимых строк
 * настоящего скриншота (`canonical-visual-assets.ts`) и таблица выдачи
 * (`mergeSerpRowsByMaterial`).
 *
 * **Сводить строки внутри `adverseVisualSidebar` нельзя.** Этот разбор
 * обслуживает снимок, сетку изображений и панели сразу и не знает, чем на
 * каждой поверхности рисуется рамка: сведение внутри него склеивало то, что
 * нарисовано порознь, — строку Яндекса со строкой Google на одном снимке и две
 * плитки одной статьи на сетке, — и лист выходил с двумя красными рамками при
 * подписи «выделено красным: 1». Подробности в `docs/ENGINEERING.md` §8, «Одна
 * строка — один материал».
 *
 * Слоем деки ключ при этом пользуются те, у кого единица — материал, а не
 * рисунок: таблица выдачи (`mergeSerpRowsByMaterial`), ворота сверки печати с
 * наблюдениями и разнос решений по прочитанным страницам
 * (`applyLinkVerdictsToEvidence`).
 *
 * Объединяем по тому, что видит читатель: домен и заголовок. Без заголовка
 * ориентируемся на адрес — иначе в одну строку склеились бы разные страницы
 * одного сайта.
 *
 * Ключ живёт здесь, а не в построителях деки, потому что им пользуется слой
 * ниже: снимок выдачи собирается до того, как появляется дека, и импортировать
 * из `orion-golden` он не может.
 */

/**
 * Хост адреса для ключа — не для печати.
 *
 * Печатный домен отвечает своим помощником (`publicDomainOf` в аналитике,
 * `domainOfUrl` в построителях: у первого свои правила публичности, у второго
 * прочерк вместо пустоты). Здесь нужен только устойчивый признак группировки,
 * поэтому неразобранный адрес даёт пустую строку и группирует такие строки по
 * оставшимся полям.
 */
function hostForKey(url: string | null | undefined): string {
  if (!url || !/^https?:\/\//iu.test(url)) return "";
  try {
    return new URL(url).hostname.replace(/^www\./u, "");
  } catch {
    return "";
  }
}

export function serpMaterialKey(
  e: {
    url?: string | null;
    domain?: string | null;
    title?: string | null;
  },
  /**
   * Ключ строки, которая материал не называет вовсе.
   *
   * Ни адреса, ни заголовка, ни домена — сводить такую строку не с чем, а
   * склеенная с такой же она молча теряет свою рамку и своё объяснение.
   * Поверхность, для которой это потеря, передаёт сюда собственный
   * идентификатор строки. Слой деки передаёт его всегда: у него один ответ на
   * «какой материал стоит за ссылкой» (`evidenceMaterialKey`), и таблица
   * выдачи спрашивает тем же ответом, что и счёт темы.
   */
  fallbackKey?: string
): string {
  if (fallbackKey && !e.url && !e.domain && !e.title) return fallbackKey;
  // Пустой домен значит то же, что отсутствующий: одна и та же строка,
  // записанная двумя способами, обязана дать один ключ. Отсюда `||`, а не `??`
  // — на переносе ключа из построителей эти два написания расходились.
  const domain = String(e.domain || hostForKey(e.url) || "")
    .toLowerCase()
    .replace(/^www\./u, "");
  const title = String(e.title ?? "")
    .trim()
    .toLowerCase()
    .replace(/\s+/gu, " ");
  if (title) return `${domain}|${title}`;
  const url = String(e.url ?? "")
    .trim()
    .toLowerCase()
    .replace(/^https?:\/\//u, "")
    .replace(/^www\./u, "")
    .replace(/\/+$/u, "");
  return url ? `url:${url}` : `domain:${domain}`;
}
