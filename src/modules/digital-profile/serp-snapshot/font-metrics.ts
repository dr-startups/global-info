/** Ширина глифа, единиц на em. */
export function glyphAdvance(codePoint: number): number {
  return ADVANCES.get(codePoint) ?? FALLBACK_ADVANCE;
}

/** Ширина строки в пикселях при кегле `fontSize` — сумма ширин глифов. */
export function textWidthPx(text: string, fontSize: number): number {
  let units = 0;
  for (const ch of String(text ?? "")) units += glyphAdvance(ch.codePointAt(0) ?? 0);
  return (units * fontSize) / DEJAVU_SANS_UNITS_PER_EM;
}
