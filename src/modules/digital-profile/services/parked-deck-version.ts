/**
 * Версия деки, на которой прогон запаркован отказом.
 *
 * У вставшего прогона два замка, и оба означают одно: «этот отказ уже был, и
 * повторять его нечем». Кнопку «Возобновить» запирает детерминированный гейт в
 * `job.lastError`, кнопку «Пересобрать отчёт» — отметка
 * `report-rebuild-failed:<код>` в предупреждениях. Пока замки не помнили, при
 * каком коде их закрыли, они переживали выкат исправления: `lastError`
 * очищает только само восстановление (то есть кнопка, которую маркер и
 * запирает), а отметку неудачной пересборки не снимает никто. Прогон, чья
 * пересборка однажды провалилась тем же кодом, оставался мёртвым навсегда —
 * при целом оплаченном сборе на диске.
 *
 * Поэтому прогон, паркуясь, записывает версию содержимого деки, а замки держат
 * ровно до её смены. **Записи нет — не держат:** так выглядят прогоны,
 * вставшие до появления этой записи, и отпереть их больше нечем. Умолчание
 * выбрано в сторону «кнопка есть»: цена ошибочного отпирания — одна
 * пересборка, которая провалится и запрётся снова, уже с версией; цена
 * ошибочного запирания — оплаченный прогон, который можно только собрать
 * заново за деньги.
 *
 * Почему версия, а не отпечаток построителей: отпечаток считает тест по
 * исходникам, а в собранном образе их может не быть. В рантайме доступна
 * версия — и она же ключ кэша пакетов, то есть ровно то, что делает пересборку
 * осмысленной.
 *
 * Модуль чистый: ни сети, ни БД.
 */

import { DECK_CONTENT_VERSION } from "../orion-golden/deck-sections/content-version";
import { isDeterministicPrepareGate } from "./prepare-gate-advice";
import { parkedOnRepeatedFailure } from "./prepare-repeat";

/** Запись в предупреждениях прогона: на какой версии деки он встал. */
export const PARKED_DECK_VERSION_PREFIX = "deck-content-version:";

/**
 * Предупреждения с версией нынешней сборки — ровно одной записью.
 *
 * Прежние записи снимаются: предупреждения схлопывают только дословные дубли,
 * а `v145` и `v146` — две разные строки, и замок читал бы первую попавшуюся.
 */
export function recordParkedDeckVersion(warnings: readonly string[]): string[] {
  return [
    ...warnings.filter((w) => !w.startsWith(PARKED_DECK_VERSION_PREFIX)),
    `${PARKED_DECK_VERSION_PREFIX}${DECK_CONTENT_VERSION}`,
  ];
}

/** Держит ли замок: прогон встал на той же версии деки, что собирается сейчас. */
export function parkedOnCurrentDeckVersion(
  warnings: readonly string[] | null | undefined
): boolean {
  return (warnings ?? []).includes(`${PARKED_DECK_VERSION_PREFIX}${DECK_CONTENT_VERSION}`);
}

/**
 * Повтор подготовки этому прогону не поможет, и версия деки с тех пор не
 * менялась.
 *
 * «Не поможет» — один вопрос с двумя источниками данных: гейт, назвавший себя в
 * тексте отказа (детерминизм известен заранее), и пометка `prepare-repeat`
 * (детерминизм доказан вторым дословно одинаковым отказом).
 *
 * Прогонам без конвейера шагов (`unified-recovery-legacy-heuristic`) тот же
 * вопрос задаётся без версии, и намеренно: отпущенный замок не открывает им
 * кнопку — ответ всё равно закрытый, — а информативная причина у запертого
 * лучше, чем общее «восстановление невозможно».
 */
export function prepareRetryIsPointless(job: {
  lastError?: string | null;
  warnings?: readonly string[] | null;
}): boolean {
  return (
    (isDeterministicPrepareGate(job.lastError) || parkedOnRepeatedFailure(job.warnings)) &&
    parkedOnCurrentDeckVersion(job.warnings)
  );
}
