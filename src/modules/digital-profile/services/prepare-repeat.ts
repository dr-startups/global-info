/**
 * Повторился ли отказ подготовки дословно — и чем это доказывается.
 *
 * Прогон DPA-2026-0046 упал сборкой деки и повторил один и тот же отказ
 * **десять раз** до `STEP_ATTEMPTS_EXHAUSTED`. Каждый круг идёт по
 * `resumeFrom: "full"` и заново оплачивает четыре стадии модели, а бюджет
 * отказов шага `REPORT_PREPARE` — десять.
 *
 * Останавливать было нечем: вопрос «лечится ли повтором» отвечался **списком
 * имён гейтов** (`DETERMINISTIC_GATES` в `prepare-gate-advice.ts`), которые
 * называют себя в тексте как `ИМЯ=`. Отказ обязательных секций в списке не
 * назван и такого маркера не несёт. Список отстаёт по построению: следующий
 * гейт снова стоил бы десяти оплат.
 *
 * Признак, который не отстаёт, — данные предыдущей попытки: **тот же код и тот
 * же текст**. Это доктрина «состояние — это данные, а не название»: список имён
 * ведёт человек, а сравнение с прошлым отказом ведут сами данные.
 *
 * Второго ответа на вопрос это не заводит. Ответ по-прежнему один
 * (`retryWouldRepeatItself` в оркестраторе), у него становится два источника:
 * маркер гейта в сообщении и предыдущая попытка на джобе. Первый паркует с
 * первой попытки — там детерминизм известен заранее; второй со второй — там он
 * доказан.
 *
 * Первая попытка остаётся платной и законной: часть ворот сборки читает текст
 * модели, и второй заход может дать другой ответ. Вторая одинаковая доказывает,
 * что не даст.
 *
 * Модуль чистый: ни сети, ни БД.
 */

/** Запись в предупреждениях прогона: запаркован повтором, а не гейтом. */
export const PREPARE_REPEATED_FAILURE_MARK = "prepare-failed-identically";

/** Отказ предыдущей попытки шага — как его хранит строка конвейера. */
export type PreviousStepFailure = {
  code?: string | null;
  message?: string | null;
};

/**
 * Отказ дословно повторяет предыдущую попытку.
 *
 * Сравнение **дословное**, и это решение, а не упрощение. Текст отказа сборки —
 * функция от собранных пакетов: одинаковые пакеты дают одинаковую строку.
 * Отличие в один знак означает другой отказ, а нормализация («по коду и первым
 * N символам») вернула бы догадку, ради ухода от которой шаг и делается.
 *
 * **Данные берутся у строки шага, а не у джобы, и это цена одной ошибки.**
 * Сначала признак читал `job.lastError`/`job.lastErrorCode` — и не срабатывал
 * на живом пути никогда: обработчик шага снимает вердикт прошлой попытки с
 * джобы **перед** новой (`unified-step-handlers.ts`, `stageForRetryAttempt`),
 * и ручное «Возобновить» делает то же. Тест этого не показал, потому что звал
 * тик напрямую, минуя обработчик. Строка шага (`dp_workflow_steps`) хранит
 * `lastError`/`lastErrorCode` до самого успеха — их пишет `applyStepOutcome`,
 * и не чистит никто. Ни нового поля, ни колонки заводить не пришлось.
 */
export function repeatsPreviousFailure(
  previous: PreviousStepFailure | null | undefined,
  code: string,
  message: string
): boolean {
  const previousMessage = previous?.message ?? "";
  const previousCode = previous?.code ?? "";
  if (!previousMessage || !previousCode) return false;
  return previousCode === code && previousMessage === message;
}

/** Прогон запаркован потому, что отказ повторился дословно. */
export function parkedOnRepeatedFailure(warnings: readonly string[] | null | undefined): boolean {
  return (warnings ?? []).includes(PREPARE_REPEATED_FAILURE_MARK);
}
