import { createHash } from "node:crypto";

/**
 * Идентичность строки выдачи: движок — её часть.
 *
 * «Страница на месте N у Яндекса» и «она же на месте M у Google» — два разных
 * факта, и оба нужны отчёту. Пока движка в хеше не было, обе записи считались
 * одной: `createMany({skipDuplicates})` молча выбрасывал вторую, и вычёркивал
 * её тот поисковик, который отработал позже. На прогоне 76 Яндекс шёл первым, и
 * дыры 1, 2, 3, 5 в таблице «Россия — Google» — это ненаписанные строки Google;
 * пересборкой отчёта их не вернуть, их просто нет.
 *
 * Запрос и регион входят в хеш там, где строка их знает (сбор по плану
 * запросов), и не входят там, где не знает (агентский сборщик пишет выдачу без
 * запроса). Оба варианта идемпотентны: повторный запуск того же сборщика по
 * тому же адресу даёт тот же хеш и попадает в `skipDuplicates`.
 *
 * После деплоя повторный сбор уже собранного кейса запишет строки со старым и
 * новым хешем — на короткое время в `search_results` будут дубли. До отчёта они
 * не доходят: слияние композита дедупит по ключу, в который движок входит.
 */
export function searchResultDedupHash(input: {
  /** Поисковик строки: GOOGLE / YANDEX. */
  engine: string;
  /** Адрес после `normalizeUrl` — сравнивать сырые адреса бессмысленно. */
  normalizedUrl: string;
  /** Запрос, которым строка найдена; у агентского сборщика его нет. */
  query?: string;
  /** Региональный контур сбора; парный запросу. */
  region?: string;
}): string {
  const parts = [input.engine, input.normalizedUrl];
  if (input.query !== undefined || input.region !== undefined) {
    parts.push(input.query ?? "", input.region ?? "");
  }
  return createHash("sha256").update(parts.join("|")).digest("hex");
}
