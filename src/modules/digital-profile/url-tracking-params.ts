/**
 * Метки отслеживания в адресе — **один список на весь продукт**.
 *
 * Вопрос «одна ли это страница» задаётся дважды и в разных слоях: слой сбора
 * дедуплицирует строки по `dedupHash` (`services/evidence-service.ts`), слой
 * деки сводит наблюдения в материал (`serp-observation/material-key.ts`).
 * Пока список меток был только у первого, `klerk.ru/materials/…` с двенадцатью
 * разными `?srsltid=` давал деке тринадцать материалов одной статьи, и таблица
 * выдачи прогона 91 печатала клиенту два соседних ряда с одним заголовком и
 * стознаковым рекламным токеном Google в адресе.
 *
 * Модуль листовой и без импортов намеренно: `material-key.ts` лежит ниже слоя
 * услуг, и тянуть в него Prisma нельзя.
 *
 * **Снимается только то, что не адресует страницу.** `?v=` YouTube, `?id=`,
 * `?page=`, `?text=` — часть адреса: без них открывается другая страница или
 * пустой проигрыватель. Метка же не меняет содержимого и отличается у двух
 * визитов одного человека.
 */

/**
 * Имена параметров-меток.
 *
 * `utm_*` — общий рекламный набор; `fbclid`/`gclid`/`yclid` — клики Facebook,
 * Google и Яндекса; `mc_*` — рассылки Mailchimp; `srsltid` — токен перехода
 * Google Merchant (именно он размножил klerk.ru); `shem` — метка Яндекса,
 * которую мы видели в адресах TAdviser.
 */
export const URL_TRACKING_PARAMS = /^(utm_|fbclid$|gclid$|yclid$|mc_|srsltid$|shem$)/i;

/**
 * Тот же адрес без меток отслеживания.
 *
 * Разбирается **строкой, а не `new URL`**, и на то две причины, обе замеренные.
 *
 * Первая: адрес приходит и без схемы. `serpMaterialKey` рассчитан на такой
 * (он сам снимает `www.` и хвостовой слэш), и ворот приёмки зовёт его
 * печатными ячейками таблицы, у которых схемы нет вовсе. Разбор через `URL`
 * такие строки возвращал бы нетронутыми, и приёмка не увидела бы двух соседних
 * рядов, различающихся только меткой, — того самого, что владелец увидел на
 * стр. 41 прогона 91.
 *
 * Вторая: `URL.toString()` перекодирует путь и значения параметров в
 * процентные последовательности. Тогда адрес с кириллицей, у которого метка
 * есть, и он же без метки давали бы **разные** ключи — дефект сохранялся бы
 * ровно там, где продукт русский.
 *
 * Строка без параметров возвращается как есть: трогать нечего.
 */
export function urlWithoutTrackingParams(raw: string): string {
  const text = String(raw ?? "").trim();
  const cut = text.search(/[?#]/u);
  if (cut < 0) return text;
  const head = text.slice(0, cut);
  const separator = text[cut]!;
  const rest = text.slice(cut + 1);
  // Якорь параметров не содержит и делится отдельно: `?a=1#b=2` — это путь с
  // параметром `a` и якорем `#b=2`, а не два параметра.
  const [queryPart = "", ...hashParts] = separator === "?" ? rest.split("#") : [];
  const hash = separator === "#" ? `#${rest}` : hashParts.length > 0 ? `#${hashParts.join("#")}` : "";
  if (separator === "#") return `${head}${hash}`;
  const kept = queryPart
    .split("&")
    .filter((pair) => pair.length > 0)
    .filter((pair) => !URL_TRACKING_PARAMS.test(pair.split("=")[0] ?? ""));
  // Порядок оставшихся параметров сохраняется: сортировать их — работа
  // `normalizeUrl`, и делать её здесь значило бы отвечать на чужой вопрос.
  return `${head}${kept.length > 0 ? `?${kept.join("&")}` : ""}${hash}`;
}
