/**
 * Дата рождения в форме сайта: маска «дд.мм.гггг» в поле и «ГГГГ-ММ-ДД» в теле запроса.
 *
 * Поле текстовое, а не `type="date"` (решение владельца 16.09.2026): календарь
 * браузера не стилизуется, а на Android открывается на сегодняшнем дне, и до года
 * рождения приходится листать. В поле живёт то, что видит человек; в формат ручки
 * его переводит `checkFormPayload`, поэтому схема ручки и её тексты не меняются.
 */

/**
 * Единственная строка про дату, которой нет в схеме ручки: схема знает только
 * «ГГГГ-ММ-ДД», и её «неверный формат» человеку, набирающему «дд.мм.гггг», не
 * подходит. На сервер неполная дата не уходит — отправку останавливает проверка формы.
 */
export const BIRTH_DATE_INCOMPLETE_MESSAGE = "Введите дату полностью: дд.мм.гггг.";

const ISO_DATE = /^\s*(\d{4})-(\d{2})-(\d{2})\s*$/u;
const MASKED_DATE = /^\s*(\d{2})\.(\d{2})\.(\d{4})\s*$/u;

/**
 * Приводит набранное к маске. Точка ставится только перед следующей группой, а не
 * после двух цифр: иначе стирание упиралось бы в точку, которую маска тут же
 * возвращает. Вставку «ГГГГ-ММ-ДД» (так дату отдают автозаполнение и копия из
 * документов) переворачивает — цифры подряд дали бы «19.85.0312».
 */
export function maskBirthDate(raw: string): string {
  const iso = ISO_DATE.exec(raw);
  const digits = iso ? `${iso[3]}${iso[2]}${iso[1]}` : raw.replace(/\D/gu, "").slice(0, 8);
  return [digits.slice(0, 2), digits.slice(2, 4), digits.slice(4, 8)].filter((part) => part !== "").join(".");
}

/**
 * Позиция курсора сразу после `digits`-й цифры маски. Поле перерисовывается
 * значением из состояния, и без этого курсор после правки в середине улетал бы в конец.
 */
export function caretAfterDigits(masked: string, digits: number): number {
  if (digits <= 0) return 0;
  let seen = 0;
  for (let i = 0; i < masked.length; i += 1) {
    if (/\d/u.test(masked[i]!)) seen += 1;
    if (seen === digits) return i + 1;
  }
  return masked.length;
}

/** «дд.мм.гггг» → «ГГГГ-ММ-ДД»; неполная или иная запись — `null`. */
export function birthDateToIso(display: string): string | null {
  const m = MASKED_DATE.exec(display);
  return m ? `${m[3]}-${m[2]}-${m[1]}` : null;
}
