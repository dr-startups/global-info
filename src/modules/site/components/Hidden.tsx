/**
 * Два способа показать, что здесь есть данные, но читать их не дают.
 *
 * `Blurred` — текст не в фокусе: видно, что это строка со словами, прочитать её
 * нельзя. Так показаны заголовки находок в примере результата: плашка на их месте
 * читалась столбиком диаграммы, а не спрятанным текстом (замечание владельца
 * 18.09.2026). Текст вымышлен и в разметку попадает целиком, поэтому выделение и
 * указатель у него выключены — скопировать «скрытое» нельзя.
 *
 * `Masked` — значение точками, как в поле пароля: имени и даты рождения на главной
 * нет нигде, и показывать их нечем даже в примере.
 */
export function Blurred({ text, label }: { text: string; label?: string }) {
  return (
    <span className="site-blur" {...(label === undefined ? {} : { role: "img", "aria-label": label })}>
      {text}
    </span>
  );
}

export function Masked({ text }: { text: string }) {
  return <span className="site-masked">{text}</span>;
}
