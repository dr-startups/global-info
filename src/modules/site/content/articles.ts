/** 200 слов в минуту: так время чтения двух статей макета совпадает с макетом. */
const WORDS_PER_MINUTE = 200;

export function readingMinutes(article: Pick<ArticleContent, "blocks">): number {
  return Math.max(1, Math.ceil(wordCount(blockTexts(article.blocks)) / WORDS_PER_MINUTE));
}

/** «2 минуты чтения» — одна подпись у статьи и у её карточки в блоге. */
export function readingTimeText(article: Pick<ArticleContent, "blocks">): string {
  const minutes = readingMinutes(article);
  return `${minutes} ${plural(minutes, ["минута", "минуты", "минут"])} чтения`;
}

