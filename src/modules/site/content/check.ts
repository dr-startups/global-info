export interface ServiceAction {
  label: string;
  variant: "accent" | "secondary" | "ghost";
  href?: string;
  /** Действие мастера, а не переход. */
  action?: "lead" | "retry";
}

export interface ServiceScreenContent {
  status: string;
  tone?: "warn" | "danger";
  title: string;
  lead: string;
  actions: ServiceAction[];
  asideTitle?: string;
  facts?: ReadonlyArray<readonly [string, string]>;
}

