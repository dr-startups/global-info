/**
 * Даты контента: в реестре — `ГГГГ-ММ-ДД` (её читают карта сайта и разметка
 * статьи), на странице — «12 сентября 2026».
 *
 * Без `Date` и часового пояса: дата текста — это день, а не момент, и полночь по
 * UTC в браузере западнее Гринвича превратилась бы в предыдущий день.
 */

const MONTHS = [
  "января",
  "февраля",
  "марта",
  "апреля",
  "мая",
  "июня",
  "июля",
  "августа",
  "сентября",
  "октября",
  "ноября",
  "декабря",
] as const;

export function formatContentDate(iso: string): string {
  const match = /^(\d{4})-(\d{2})-(\d{2})$/u.exec(iso);
  if (!match) throw new Error(`Дата контента не в формате ГГГГ-ММ-ДД: ${iso}`);
  const [, year, month, day] = match;
  return `${Number(day)} ${MONTHS[Number(month) - 1]} ${year}`;
}
