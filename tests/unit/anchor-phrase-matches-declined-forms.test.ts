/**
 * Якорь-фраза узнаётся в падежных формах, но не в однокоренном чужом слове.
 *
 * Прогон DPA-2026-0049 («Егоров Алексей Евгеньевич», судья): материал считался
 * «о субъекте» по одному совпадению ФИО, и в отчёт попали офтальмолог, депутат
 * и четыре ИП. Якорь оператора — то, чем материал подтверждается сверх имени,
 * и он обязан переживать склонение: оператор пишет «Арбитражный суд
 * Краснодарского края», а в выдаче стоит «председатель Арбитражного суда
 * Краснодарского края».
 *
 * Совпадение считается по основам, а не по префиксу: рецензия проекта нашла,
 * что префиксное сравнение делает «судья» ⊂ «судьбы» и приписывает субъекту
 * рязанского депутата. Основа отделяется только известным окончанием, и
 * остаток проверяется тем же списком окончаний.
 */

import { describe, expect, it } from "vitest";
import {
  anchorPhraseStems,
  phraseMatchesText,
} from "@/modules/digital-profile/orion-golden/analytics/subject-anchors";

describe("основы якорь-фразы", () => {
  it("окончание отделяется, короткое слово остаётся собой", () => {
    expect(anchorPhraseStems("Арбитражный суд Краснодарского края")).toEqual([
      "арбитражн",
      "краснодарск",
      "кра",
    ]);
    expect(anchorPhraseStems("судья")).toEqual(["судь"]);
  });

  it("географический классификатор в основы не входит: он сокращается в выдаче", () => {
    // «станица Красноармейская» в выдаче пишется «ст.Красноармейской».
    expect(anchorPhraseStems("станица Красноармейская")).toEqual(["красноармейск"]);
    expect(anchorPhraseStems("город Краснодар")).toEqual(["краснодар"]);
  });
});

describe("совпадение якорь-фразы с текстом", () => {
  it("падежные формы совпадают", () => {
    const anchor = "Арбитражный суд Краснодарского края";
    expect(
      phraseMatchesText(
        "Егоров Алексей Евгеньевич Председатель Арбитражного суда Краснодарского края",
        anchor
      )
    ).toBe(true);
    expect(phraseMatchesText("Арбитражный суд Краснодарского края — официальный сайт", anchor)).toBe(true);
    expect(phraseMatchesText("Арбитражному суду Краснодарскому краю", anchor)).toBe(true);
  });

  it("станица узнаётся в сокращении", () => {
    expect(phraseMatchesText("Родился 30 ноября 1977г. в ст.Красноармейской", "станица Красноармейская")).toBe(true);
  });

  it("однокоренное чужое слово якорем не считается", () => {
    expect(phraseMatchesText("человек непростой судьбы", "судья")).toBe(false);
    expect(phraseMatchesText("коллегия судей области", "судья")).toBe(false);
    expect(phraseMatchesText("судейская этика", "судья")).toBe(false);
    expect(phraseMatchesText("Судья Егоров на портале Право.ру", "судья")).toBe(true);
  });

  it("часть фразы совпадением не является", () => {
    const anchor = "Арбитражный суд Краснодарского края";
    expect(phraseMatchesText("Арбитражный суд Ростовской области", anchor)).toBe(false);
    expect(phraseMatchesText("Краснодарский краевой суд", anchor)).toBe(false);
  });

  it("совпадение по токену, а не по подстроке", () => {
    // Подстрочного совпадения нет: «красноармеец» основой «красноармейск» не
    // покрывается.
    expect(phraseMatchesText("красноармеец Егоров", "станица Красноармейская")).toBe(false);
  });

  it("предел правила назван: однокоренное слово того же корня совпадёт", () => {
    // Основа смысла не знает. Вторая линия защиты — панель персон: она
    // показывает оператору строки, на которых якорь сработал.
    expect(phraseMatchesText("красноармейскими методами", "станица Красноармейская")).toBe(true);
  });
});
