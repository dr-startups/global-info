/**
 * Дата рождения — самый сильный различитель тёзок, и она обязана работать в обе
 * стороны: своя дата подтверждает материал, чужая — опровергает.
 *
 * Прогон 0049: у депутата гордумы Краснодара в сниппете стоит «Родился: 10
 * августа 1983 года», у боксёра «born 16 June 1991», у кандидата «15.06.54
 * г.р.» — а дата рождения кейса (30.11.1977) до разметки не доходила вовсе.
 *
 * Дата без слова-сигнала конфликтом не является: «ИП зарегистрирован
 * 23.11.2000» — дата регистрации, а не рождения.
 */

import { describe, expect, it } from "vitest";
import {
  birthDateMatch,
  foreignBirthDates,
} from "@/modules/digital-profile/orion-golden/analytics/subject-anchors";

const OWN = "1977-11-30";

describe("своя дата рождения", () => {
  it("узнаётся в трёх написаниях", () => {
    expect(birthDateMatch("Родился 30.11.1977г. в ст.Красноармейской", OWN)).toBe("30.11.1977");
    expect(birthDateMatch("Алексей Евгеньевич Егоров родился 30 ноября 1977 года", OWN)).toBe("30 ноября 1977");
    expect(birthDateMatch("birth date 1977-11-30", OWN)).toBe("1977-11-30");
    expect(birthDateMatch("Родился 1 ноября 1982 года", OWN)).toBeNull();
  });
});

describe("чужая дата рождения", () => {
  it("ловится рядом со словом-сигналом, включая двузначный год", () => {
    expect(foreignBirthDates("Родился: 10 августа 1983 года в п. Чегдомын", OWN)).toEqual(["10 августа 1983"]);
    expect(foreignBirthDates("Егоров Алексей Евгеньевич, 15.06.54 г.р., кандидат", OWN)).toEqual(["15.06.54"]);
    expect(foreignBirthDates("Alexey Egorov was born 16 June 1991", OWN)).toEqual(["16 June 1991"]);
  });

  it("слово-сигнал далеко — дата не о рождении", () => {
    // Окно проверяется, а не наличие слова где-нибудь на странице: иначе любая
    // дата на биографической странице объявлялась бы чужой датой рождения.
    const text =
      "Родился в Краснодарском крае, окончил университет, работал в органах прокуратуры края семь лет, ИП зарегистрирован 23.11.2000";
    expect(foreignBirthDates(text, OWN)).toEqual([]);
  });

  it("дата без слова-сигнала конфликтом не является", () => {
    expect(foreignBirthDates("ИП Егоров Алексей Евгеньевич зарегистрирован 23.11.2000", OWN)).toEqual([]);
    expect(foreignBirthDates("Указ подписан 17.10.2016", OWN)).toEqual([]);
  });

  it("своя дата на странице отменяет чужую: список судей — не конфликт", () => {
    const text = "Егоров Алексей Евгеньевич родился 30.11.1977; Иванов Пётр родился 12.03.1969";
    expect(foreignBirthDates(text, OWN)).toEqual([]);
  });

  it("без своей даты чужих не бывает — сравнивать не с чем", () => {
    expect(foreignBirthDates("Родился 10 августа 1983 года", null)).toEqual([]);
  });
});
