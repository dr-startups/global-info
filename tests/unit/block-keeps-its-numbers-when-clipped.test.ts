/**
 * Числа блока сбрасываются последними (шаг 0144).
 *
 * Подгонка буллета под бюджет сбрасывает целые строки в известном порядке.
 * Числа блока («Всего по теме: …») стояли в этом порядке третьими — раньше
 * второй цитаты, — и ворота инвариантов нашли четыре блока на стр. 5 отчёта
 * Алекперова 21.09.2026: с цитатой, с рамкой «Найдены материалы…» и без
 * единого числа.
 *
 * Блок, обещающий цитаты, обязан называть их количество: «сколько всего» —
 * то, ради чего читатель смотрит на тему. Вторая цитата иллюстрирует, числа
 * отвечают.
 */

import { describe, expect, it } from "vitest";
import { fitStructuredBullet } from "@/modules/digital-profile/orion-golden/deck-sections/fragment-builders/shared";

const BLOCK = [
  "«Корпоративное владение»",
  "Найдены материалы о владении компаниями и структуре собственности:",
  "«О хороших манерах владельцев крупного бизнеса мы разговариваем с главой компании ЛУКОЙЛ Вагитом Алекперовым, который рассказал о принципах.» — источник (kommersant.ru/doc/1)",
  "«Вторая цитата темы, которая иллюстрирует тот же сюжет и занимает столько же места в буллете страницы.» — источник (rbc.ru/doc/2)",
  "Всего по теме: 12 материалов по отчёту, с негативным контекстом — 4.",
  "Где видно: kommersant.ru, rbc.ru.",
  "Для банка или партнёра владение компаниями претензией не является, но состав долей обычно просят подтвердить документами.",
].join("\n");

describe("подгонка блока под бюджет", () => {
  it("Ч1: при тесном бюджете уходит вторая цитата, а числа остаются", () => {
    const out = fitStructuredBullet(BLOCK, 420);
    expect(out).toContain("Всего по теме: 12 материалов");
    expect(out).not.toContain("Вторая цитата темы");
  });

  it("Ч2: первая цитата и рамка переживают сброс", () => {
    const out = fitStructuredBullet(BLOCK, 420);
    expect(out).toContain("Найдены материалы о владении");
    expect(out).toContain("хороших манерах");
  });

  it("Ч3: просторный бюджет не роняет ничего", () => {
    const out = fitStructuredBullet(BLOCK, 2000);
    expect(out).toContain("Вторая цитата темы");
    expect(out).toContain("Где видно:");
    expect(out).toContain("Всего по теме: 12 материалов");
  });
});
