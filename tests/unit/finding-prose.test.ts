import { describe, expect, it } from "vitest";
import {
  composeFindingProse,
  composeSlideNarrative,
} from "@/modules/digital-profile/orion-golden/deck-sections/run-deck-build";

/**
 * Текст находки собирается абзацем вместо анкеты из трёх подписей.
 *
 * Закреплены оба свойства, ради которых это делалось: подписи не возвращаются
 * в клиентский текст, и повтор уже показанного факта не попадает в абзац.
 * Второе — не украшение: пока текст ехал под подписью «Что обнаружено:»,
 * дословный повтор первого буллета выглядел отдельной графой и в глаза не
 * бросался; стоило подпись убрать, и один и тот же факт пошёл дважды подряд.
 */

describe("текст находки — абзац, а не анкета", () => {
  it("склеивает найденное и его значение в один абзац", () => {
    const out = composeFindingProse({
      whatWasFound: "В выдаче есть материалы о судебном разбирательстве",
      whyItMatters: "Они видны при первичной проверке контрагентом",
    });
    expect(out).toBe(
      "В выдаче есть материалы о судебном разбирательстве. Они видны при первичной проверке контрагентом."
    );
  });

  it("не добавляет подписей анкеты", () => {
    const out = composeFindingProse({
      whatWasFound: "Найдены публикации",
      whyItMatters: "Это влияет на решение",
      whatToCheck: "Сверить первоисточники",
    });
    expect(out).not.toMatch(/Что обнаружено|Почему важно|Что проверить/u);
  });

  it("вывод остаётся отдельным предложением с новой строки", () => {
    const out = composeFindingProse({
      whatWasFound: "Найдены публикации.",
      whatToCheck: "Сверить первоисточники",
    });
    expect(out).toBe("Найдены публикации.\nСверить первоисточники.");
  });

  it("не повторяет то, что уже стоит буллетом", () => {
    const shown = "«Судебные материалы»: уровень внимания — критический.";
    const out = composeFindingProse({
      whatWasFound: shown,
      whyItMatters: "Материалы видны при первичной проверке.",
      bullets: [shown],
    });
    expect(out).toBe("Материалы видны при первичной проверке.");
  });

  it("не повторяет то, что уже сказано во вводном абзаце", () => {
    const out = composeFindingProse({
      narrative: "Найдены публикации по теме.",
      whatWasFound: "найдены публикации по теме",
      whyItMatters: "Это влияет на решение.",
    });
    expect(out).toBe("Это влияет на решение.");
  });

  it("повтор ловится независимо от регистра, пробелов и пунктуации", () => {
    const out = composeFindingProse({
      bullets: ["«Судебные   материалы»: уровень внимания — критический!"],
      whatWasFound: "судебные материалы уровень внимания критический",
    });
    expect(out).toBeUndefined();
  });

  it("пустой вход не даёт пустого абзаца", () => {
    expect(composeFindingProse({})).toBeUndefined();
    expect(composeFindingProse({ whatWasFound: "   " })).toBeUndefined();
  });

  it("не приписывает вторую точку к законченному предложению", () => {
    const out = composeFindingProse({ whatWasFound: "Материалы найдены.", whyItMatters: "Важно!" });
    expect(out).toBe("Материалы найдены. Важно!");
  });
});

/**
 * Подзаголовок склеивается с абзацем — и на резюме давал «Итоговая оценка:
 * Высокий риск / Итоговая оценка: высокий риск. Основные основания: …», то есть
 * одну фразу дважды подряд разным регистром.
 */
describe("подзаголовок и абзац", () => {
  it("не повторяет подзаголовок, которым абзац и начинается", () => {
    expect(
      composeSlideNarrative(
        "Итоговая оценка: Высокий риск",
        "Итоговая оценка: высокий риск. Основные основания: деловые связи."
      )
    ).toBe("Итоговая оценка: высокий риск. Основные основания: деловые связи.");
  });

  it("оставляет подзаголовок, когда абзац говорит о другом", () => {
    expect(composeSlideNarrative("Россия", "В выдаче найдены публикации.")).toBe(
      "Россия\nВ выдаче найдены публикации."
    );
  });

  it("совпадение в середине абзаца — не дубль заголовка", () => {
    const out = composeSlideNarrative("Офшоры", "Найдены материалы. Офшоры упомянуты вскользь.");
    expect(out).toBe("Офшоры\nНайдены материалы. Офшоры упомянуты вскользь.");
  });

  it("работает, когда одна из частей пуста", () => {
    expect(composeSlideNarrative(undefined, "Только абзац.")).toBe("Только абзац.");
    expect(composeSlideNarrative("Только подзаголовок", undefined)).toBe("Только подзаголовок");
    expect(composeSlideNarrative(undefined, undefined)).toBeUndefined();
  });
});
