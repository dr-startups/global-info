import { describe, expect, it } from "vitest";
import { isValidInn } from "@/modules/self-check/inn";

/**
 * ИНН принимается только с верными контрольными разрядами.
 *
 * Поле ИНН на форме сайта необязательно, но введённый номер попадает в профиль
 * субъекта как его признак. Без контрольной суммы номером считалось бы любое
 * число нужной длины — например, хвост дроби «11398.600000000002».
 *
 * Номера здесь — опубликованный ИНН юрлица и синтетические: их контрольные
 * разряды посчитаны отдельно, по алгоритму ФНС, а не этим кодом. ИНН людей из
 * прогонов в тесты не берутся.
 */

describe("контрольная сумма ИНН", () => {
  it.each([
    ["юрлицо, опубликованный номер", "7707083893"],
    ["юрлицо, синтетический номер", "5024012340"],
    ["физлицо, синтетический номер", "500301123458"],
    ["физлицо, второй синтетический номер", "781112345647"],
  ])("верный ИНН принимается: %s", (_label, inn) => {
    expect(isValidInn(inn)).toBe(true);
  });

  it.each([
    ["изменена последняя цифра десятизначного", "7707083894"],
    ["неверен двенадцатый разряд", "500301123459"],
    ["неверен одиннадцатый разряд", "500301123468"],
    ["хвост дроби той же длины", "600000000002"],
  ])("номер нужной длины без верной суммы отвергается: %s", (_label, inn) => {
    expect(isValidInn(inn)).toBe(false);
  });

  it.each([
    ["9 цифр", "770708389"],
    ["11 цифр", "77070838931"],
    ["13 цифр", "5003011234580"],
    ["буква внутри", "77070838a3"],
    ["дефис внутри", "7707-083893"],
    ["пусто", ""],
  ])("не ИНН по форме: %s", (_label, inn) => {
    expect(isValidInn(inn)).toBe(false);
  });

  it("пробелы по краям — не часть номера", () => {
    expect(isValidInn(" 7707083893 ")).toBe(true);
  });

  it("отсутствующее значение из формы — не ИНН, а не исключение", () => {
    expect(isValidInn(undefined as unknown as string)).toBe(false);
    expect(isValidInn(null as unknown as string)).toBe(false);
  });
});
