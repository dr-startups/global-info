/**
 * Таблица метрик не печатает две строки, которые клиент не различает.
 *
 * `p25_uae_metrics` эталона-72 печатал подряд
 *
 *   Поисковые системы | Изображения в поиске | 19 | негативных: 1; …: 6
 *   Поисковые системы | Изображения в поиске | 30 | негативных: 2; …: 9
 *
 * Строка строится по одной на единицу поверхности, а у всех трёх единиц
 * `images` поле `engine` равно `null` — «Поисковые системы» честно. Различает
 * эти две единицы **регион** (`INTERNATIONAL` и `UAE`), а региона в таблице нет
 * ни в одной колонке: клиент видит один показатель дважды с разными числами и
 * не может сказать, чем они отличаются. Сторожа нет — ворот
 * `serpTableAddressesPrintedOnce` смотрит на полосу адреса, которой у таблицы
 * метрик не бывает.
 *
 * Свойство: строки, совпавшие по паре «Система + Показатель», сводятся в одну;
 * объём — сумма, счётчики складываются **числами**, а не склеиваются строками.
 */

import { describe, expect, it } from "vitest";
import { mergeMetricRows } from "@/modules/digital-profile/orion-golden/deck-sections/fragment-builders/regional-summary";

describe("строки метрик сводятся по паре «Система + Показатель»", () => {
  it("две единицы поверхности дают одну строку с суммой", () => {
    expect(
      mergeMetricRows([
        { engine: "Поисковые системы", label: "Изображения в поиске", total: 19, adverse: 1, matched: 6 },
        { engine: "Поисковые системы", label: "Изображения в поиске", total: 30, adverse: 2, matched: 9 },
      ])
    ).toEqual([
      ["Поисковые системы", "Изображения в поиске", "49", "негативных: 3; подтверждена связь с лицом: 15"],
    ]);
  });

  it("уникальные пары не сливаются и порядок сохраняется", () => {
    // RU-таблица эталона: 13 строк, все пары уникальны — их 13 и остаётся.
    const rows = mergeMetricRows([
      { engine: "Яндекс", label: "Результаты поиска", total: 30, adverse: 1, matched: 27 },
      { engine: "Google", label: "Результаты поиска", total: 20, adverse: 2, matched: 15 },
      { engine: "Google", label: "Поисковые подсказки", total: 8, adverse: 0, matched: 6 },
    ]);
    expect(rows).toHaveLength(3);
    expect(rows.map((r) => r[0])).toEqual(["Яндекс", "Google", "Google"]);
  });

  it("порядок слитой строки — место первой из слитых", () => {
    const rows = mergeMetricRows([
      { engine: "Поисковые системы", label: "Изображения в поиске", total: 19, adverse: 1, matched: 6 },
      { engine: "Google", label: "Результаты поиска", total: 20, adverse: 0, matched: 18 },
      { engine: "Поисковые системы", label: "Изображения в поиске", total: 30, adverse: 2, matched: 9 },
    ]);
    expect(rows.map((r) => r[1])).toEqual(["Изображения в поиске", "Результаты поиска"]);
    expect(rows[0]![2]).toBe("49");
  });

  it("слияние с нулевыми счётчиками говорит словами, а не «негативных: 0»", () => {
    expect(
      mergeMetricRows([
        { engine: "Google", label: "Связанные запросы", total: 4, adverse: 0, matched: 0 },
        { engine: "Google", label: "Связанные запросы", total: 6, adverse: 0, matched: 0 },
      ])[0]![3]
    ).toBe("негативных сигналов не выявлено");
  });

  it("единичная строка печатается той же формулировкой", () => {
    expect(
      mergeMetricRows([
        { engine: "Яндекс", label: "Поисковые подсказки", total: 10, adverse: 0, matched: 9 },
      ])[0]![3]
    ).toBe("подтверждена связь с лицом: 9");
  });
});
