import { describe, expect, it } from "vitest";
import { dictionaryHitIsNegated } from "../../src/modules/digital-profile/config/negated-dictionary-hit";

/**
 * Отрицание рядом со словом снимает совпадение — в обе стороны.
 *
 * Шаг 15, J1: в отчёт попала тема «Финансовые претензии / долговые споры»,
 * подпёртая материалом, который утверждает **отсутствие** претензий: «…не было
 * выставленных претензий от партнёров и клиентов». Словарь поймал «претензий»
 * и не заметил отрицания.
 *
 * Защита была односторонней — только «отрицание перед словом», — а по-русски
 * опровержение чаще стоит **после** предмета: «обвинения не подтвердились»,
 * «претензии сняты», «дело прекращено». Отчёт читает сам субъект, и ложный
 * «Нежелательный» на опровержении предлагает ему убирать материал, который его
 * оправдывает.
 *
 * Здесь закреплён предикат целиком: обе стороны окна, один список оборотов на
 * все словари и правило «снято, если снято каждое вхождение».
 */

const CLAIMS = /банкрот|bankrupt|долг\w*|debt|взыскан|неисполнен|lawsuit|претенз|неплатеж/iu;
const CRIMINAL = /уголов|criminal|арест|arrest|суд(?!острое)|court/iu;
/**
 * Словарь обвинения задан здесь, а не взят из конфига, намеренно: корни
 * «обвин» и «избие» появятся в `adversePatterns` следующей работой, а предикат
 * обязан работать на любом словаре — это его единственный аргумент.
 */
const ACCUSATION = /обвин|избие|нападени|насил/iu;

describe("отрицание перед словом темы", () => {
  it("ловит ровно тот случай из прогона", () => {
    expect(
      dictionaryHitIsNegated(
        "По компаниям, которыми руководит или руководил ДУРОВ ПАВЕЛ ВАЛЕРЬЕВИЧ " +
          "не было выставленных претензий от партнёров и клиентов на 07.07.2026.",
        CLAIMS
      )
    ).toBe(true);
  });

  it("узнаёт другие обороты отрицания", () => {
    expect(dictionaryHitIsNegated("Не выявлено признаков банкротства", CLAIMS)).toBe(true);
    expect(dictionaryHitIsNegated("Отсутствуют долги перед бюджетом", CLAIMS)).toBe(true);
  });

  it("утверждение о наличии темой остаётся", () => {
    expect(dictionaryHitIsNegated("Выставлены претензии на 40 млн", CLAIMS)).toBe(false);
    expect(dictionaryHitIsNegated("Компания признана банкротом", CLAIMS)).toBe(false);
  });

  it("отрицание, относящееся к другому, тему не снимает", () => {
    // «не смог оспорить претензии» — претензии есть.
    expect(dictionaryHitIsNegated("Не смог оспорить выставленные претензии", CLAIMS)).toBe(false);
    // «дело не закрыто» — дело есть.
    expect(dictionaryHitIsNegated("Уголовное дело не закрыто", CRIMINAL)).toBe(false);
  });

  it("текст без слова темы отрицанием не считается", () => {
    expect(dictionaryHitIsNegated("Обычный деловой профиль", CLAIMS)).toBe(false);
    expect(dictionaryHitIsNegated("", CLAIMS)).toBe(false);
  });

  it("далёкое отрицание не дотягивается", () => {
    expect(
      dictionaryHitIsNegated(
        "Не было ни одного повода для беспокойства у партнёров и клиентов, однако претензии выставлены",
        CLAIMS
      )
    ).toBe(false);
    // Цена одного числа окна названа: у «не было» четыре слова до «уголовного»,
    // и материал, говорящий «оснований не было», метку сохраняет. Прежняя
    // редакция дотягивалась сюда потому, что окно росло вместе с длиной оборота,
    // — то есть у окна было второе число.
    expect(
      dictionaryHitIsNegated("Не было никаких оснований для возбуждения уголовного дела", CRIMINAL)
    ).toBe(false);
  });
});

describe("отрицание после слова снимает совпадение", () => {
  it("опровержение стоит следом за словом", () => {
    expect(dictionaryHitIsNegated("Обвинения не подтвердились", ACCUSATION)).toBe(true);
    expect(dictionaryHitIsNegated("Обвинения в избиении сняты", ACCUSATION)).toBe(true);
    expect(dictionaryHitIsNegated("Уголовное дело прекращено", CRIMINAL)).toBe(true);
  });

  it("порядок слов больше не решает", () => {
    // Односторонность защиты была закреплена этой же парой: до окна вперёд
    // первая строка совпадение сохраняла, вторая снимала.
    expect(dictionaryHitIsNegated("Признаков банкротства не выявлено", CLAIMS)).toBe(true);
    expect(dictionaryHitIsNegated("Не выявлено признаков банкротства", CLAIMS)).toBe(true);
  });

  it("слово внутри самого оборота опровержения снято вместе с ним", () => {
    // «снял обвинения» — оборот, который несёт слово словаря в себе: снятым
    // должно быть и оно, иначе опровержение читается как обвинение.
    expect(dictionaryHitIsNegated("Суд снял обвинения", ACCUSATION)).toBe(true);
  });

  it("неснятое вхождение оставляет совпадение", () => {
    // «Суд отказал» снимает «суд» и дотягивается до «обвинений», но «избиение»
    // стоит за окном — материал остаётся обвинением.
    expect(
      dictionaryHitIsNegated(
        "Суд отказал в иске, но обвинения в избиении остаются",
        /суд(?!острое)|обвин|избие/iu
      )
    ).toBe(false);
  });

  it("окно ограничено и после слова", () => {
    expect(dictionaryHitIsNegated("Обвинения в избиении не подтвердились", ACCUSATION)).toBe(true);
    expect(
      dictionaryHitIsNegated(
        "Обвинения в избиении на Красной площади в суде не подтвердились",
        ACCUSATION
      )
    ).toBe(false);
  });

  it("оборот не переходит через «но», «однако» и «;»", () => {
    // Противительный союз — заявление, что негативное продолжается, и окно
    // обязано на нём кончаться. «Претензий не было» снимает претензии, но не
    // взысканный долг во второй части: иначе отчёт молчит о том, что источник
    // прямо утверждает.
    expect(dictionaryHitIsNegated("Претензий не было, но долг взыскан в суде", CLAIMS)).toBe(false);
    expect(
      dictionaryHitIsNegated("Претензии сняты, однако долг взыскан", CLAIMS)
    ).toBe(false);
    expect(
      dictionaryHitIsNegated("Претензии сняты; долг взыскан в суде", CLAIMS)
    ).toBe(false);
    // Без союза окно работает как прежде.
    expect(dictionaryHitIsNegated("Претензии сняты", CLAIMS)).toBe(true);
  });

  it("окно кончается ровно на четвёртом слове — в обе стороны", () => {
    // Число окна — единственный числовой рычаг конструкции, и держат его эти
    // четыре строки: три слова между оборотом и словом снимают, четыре — нет.
    expect(dictionaryHitIsNegated("Обвинения в жестоком избиении не подтвердились", ACCUSATION)).toBe(
      true
    );
    expect(
      dictionaryHitIsNegated("Обвинения в особо жестоком избиении не подтвердились", ACCUSATION)
    ).toBe(false);
    expect(dictionaryHitIsNegated("Не выявлено ни одного признака банкротства", CLAIMS)).toBe(true);
    expect(
      dictionaryHitIsNegated("Не выявлено ни одного явного признака банкротства", CLAIMS)
    ).toBe(false);
  });

  it("голый квантор совпадения не снимает — ни назад, ни вперёд", () => {
    // «нет», «без», «no» сами по себе ничего не опровергают: в заголовке они
    // относятся к чему угодно, а окно в обе стороны отдало бы им соседнее слово
    // словаря. «Обыск прошёл без понятых» — обыск с нарушением, и метку он
    // терять не должен.
    expect(dictionaryHitIsNegated("Нет претензий", CLAIMS)).toBe(false);
    expect(dictionaryHitIsNegated("Уголовное дело: комментариев нет", CRIMINAL)).toBe(false);
    expect(dictionaryHitIsNegated("Обыск в офисе прошёл без понятых", /обыск/iu)).toBe(false);
    expect(dictionaryHitIsNegated("Sanctions review: no comment", /sanction/iu)).toBe(false);
  });
});
