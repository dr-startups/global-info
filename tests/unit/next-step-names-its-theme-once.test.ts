/**
 * Проверка первоисточников оборачивает название один раз (шаг 0145).
 *
 * Строка «Сверить первоисточники и статус материалов по теме «X»» печаталась в
 * двух местах: у темы и у сюжета. Шаг 0144 поправил обёртку только у темы, а на
 * стр. 3 отчёта Алекперова 21.09.2026 «»» пришло от сюжета — «Стратегия,
 * показатели и деятельность компании «Лукойл»». Один вопрос — один ответ:
 * строку строит одна функция.
 */

import { describe, expect, it } from "vitest";
import { themeSourceCheckLine } from "@/modules/digital-profile/orion-golden/analytics/client-summary-pack-builder";

describe("строка проверки первоисточников", () => {
  it("С1: название с кавычками внутри не даёт «« или »»", () => {
    const line = themeSourceCheckLine(
      "Стратегия, показатели и деятельность компании «Лукойл»"
    );
    expect(line).not.toMatch(/»»|««/u);
    expect(line).toContain("Лукойл");
    expect(line).toBe(
      "Сверить первоисточники и статус материалов по теме «Стратегия, показатели и деятельность компании „Лукойл“»."
    );
  });

  it("С2: название без кавычек оборачивается ёлочками", () => {
    expect(themeSourceCheckLine("Офшоры и финансовая прозрачность")).toBe(
      "Сверить первоисточники и статус материалов по теме «Офшоры и финансовая прозрачность»."
    );
  });
});
