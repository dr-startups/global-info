/**
 * ИНН — идентификатор только тогда, когда его назвал оператор.
 *
 * В прогоне 0049 три чужих ИНН были добыты из корпуса по соседству с ФИО и
 * стали `strongIdentifiers`: 44 строки чужих людей получили
 * `strong_identifier_match` 0.98, и он же перебивал чужое отчество.
 *
 * Здесь закрепляются правила чтения ИНН из текста: контрольная сумма (число из
 * дроби «11398.600000000002» ИНН не является), свой ИНН на странице сильнее
 * чужого, а страница с одним чужим ИНН при неизвестном своём — «реестр, не
 * проверить», а не совпадение.
 */

import { describe, expect, it } from "vitest";
import { innsInText, isValidInn } from "@/modules/digital-profile/orion-golden/analytics/subject-anchors";

describe("чтение ИНН из текста", () => {
  it("контрольная сумма отсекает число, которое не ИНН", () => {
    expect(isValidInn("231112942662")).toBe(true);
    expect(isValidInn("772809603828")).toBe(true);
    expect(isValidInn("600000000002")).toBe(false);
    expect(isValidInn("12345")).toBe(false);
  });

  it("двенадцать цифр читаются только рядом со словом ИНН или на реестровой странице", () => {
    expect(innsInText("Егоров Алексей Евгеньевич ИНН 231112942662")).toEqual(["231112942662"]);
    expect(innsInText("площадь 11398.600000000002 м²")).toEqual([]);
    expect(innsInText("Егоров Алексей Евгеньевич 231112942662")).toEqual([]);
  });

  it("слово ИНН далеко — число не идентификатор", () => {
    const text =
      "ИНН организации указан в реквизитах на официальном сайте арбитражного суда края, а ниже стоит номер дела 231112942662";
    expect(innsInText(text)).toEqual([]);
  });
});
