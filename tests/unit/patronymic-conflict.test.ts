import { describe, expect, it } from "vitest";
import {
  conflictingPatronymics,
  hasPatronymicConflict,
} from "@/modules/digital-profile/orion-golden/analytics/patronymic-conflict";

const KERIMOV = {
  lastName: "Керимов",
  patronymics: ["Абусаидович"],
};

const DUROV = {
  lastName: "Дуров",
  patronymics: ["Валерьевич"],
};

describe("чужое отчество рядом с фамилией", () => {
  it("узнаёт другого человека в именной тройке", () => {
    expect(
      conflictingPatronymics("ИП Дуров Павел Юрьевич — ОГРНИП: 324774600790305", DUROV)
    ).toEqual(["юрьевич"]);
  });

  it("собственное отчество субъекта конфликтом не считает", () => {
    expect(conflictingPatronymics("Керимов Сулейман Абусаидович — сенатор", KERIMOV)).toEqual([]);
  });

  it("далёкое от фамилии отчество к субъекту не относит", () => {
    const text =
      "Керимов выступил на заседании. " +
      "Много лет спустя об этом вспоминал совершенно посторонний Иванов Пётр Сергеевич.";
    expect(conflictingPatronymics(text, KERIMOV)).toEqual([]);
  });
});

describe("обрубки слов отчествами не считаются", () => {
  /**
   * Разбор живого прогона: из 41 материала, отклонённого как «про другое
   * лицо», 30 отклонены по обрубкам собственного отчества субъекта —
   * «идович», «бусаидович», «саидович», «дович», «аидович». Среди
   * потерянного была статья о самом субъекте в Википедии.
   */
  it("длинное собственное отчество не превращается в чужое", () => {
    const text =
      "Керимов, Сулейман Абусаидович — Википедия. " +
      "Сулейман Абусаидович Керимов (род. 12 марта 1966, Дербент) — российский " +
      "предприниматель и политик, сенатор Российской Федерации от Дагестана.";
    expect(conflictingPatronymics(text, KERIMOV)).toEqual([]);
    expect(hasPatronymicConflict(text, KERIMOV)).toBe(false);
  });

  it("отчество, попавшее ровно на границу окна, читается целиком", () => {
    // Расстояние подобрано так, чтобы граница окна соседства (40 знаков от
    // фамилии) пришлась внутрь слова «Абусаидович»: обрубок «идович» — ровно
    // тот, что отклонил статью о субъекте на живом прогоне.
    const text = `Сулейман Абусаидович${"·".repeat(34)}Керимов`;
    expect(conflictingPatronymics(text, KERIMOV)).toEqual([]);
  });

  it("обрубок на краю окна соседства не выдумывается", () => {
    // Фамилия в самом начале, отчество — за границей окна в 40 знаков.
    const text = `Керимов ${"и".repeat(60)} Абусаидович`;
    expect(conflictingPatronymics(text, KERIMOV)).toEqual([]);
  });
});

describe("обычные слова на «-ич»", () => {
  it("не объявляют материал чужим", () => {
    for (const word of ["москвич", "кулич", "паралич", "экономический"]) {
      expect(conflictingPatronymics(`Керимов и ${word} в одном тексте`, KERIMOV)).toEqual([]);
    }
  });

  it("но настоящее короткое отчество остаётся конфликтом", () => {
    expect(conflictingPatronymics("Керимов Пётр Ильич подписал документ", KERIMOV)).toEqual([
      "ильич",
    ]);
  });
});

describe("границы применимости", () => {
  it("без собственного отчества модуль молчит", () => {
    expect(
      conflictingPatronymics("Керимов Сулейман Абусаидович", { lastName: "Керимов", patronymics: [] })
    ).toEqual([]);
  });

  it("без фамилии в тексте сравнивать не с чем", () => {
    expect(conflictingPatronymics("Пётр Сергеевич выступил на форуме", KERIMOV)).toEqual([]);
  });
});
