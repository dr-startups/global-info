import { describe, expect, it } from "vitest";
import {
  conflictingPatronymics,
  hasPatronymicConflict,
} from "@/modules/digital-profile/orion-golden/analytics/patronymic-conflict";

const KERIMOV = {
  lastName: "Керимов",
  firstNames: ["Сулейман"],
  patronymics: ["Абусаидович"],
};

const DUROV = {
  lastName: "Дуров",
  firstNames: ["Павел"],
  patronymics: ["Валерьевич"],
};

/** Субъект прогона 14.08: Юнусов Тимур Ильдарович, псевдоним «Тимати». */
const YUNUSOV = {
  lastName: "Юнусов",
  lastNameVariants: ["Юнусова"],
  firstNames: ["Тимур", "Тимати"],
  patronymics: ["Ильдарович"],
};

describe("чужое отчество рядом с фамилией", () => {
  it("узнаёт другого человека в именной тройке", () => {
    expect(
      conflictingPatronymics("ИП Дуров Павел Юрьевич — ОГРНИП: 324774600790305", DUROV)
    ).toEqual(["юрьевич"]);
  });

  it("собственное отчество субъекта конфликтом не считает", () => {
    expect(conflictingPatronymics("Керимов Сулейман Абусаидович — сенатор", KERIMOV)).toEqual([]);
  });

  it("далёкое от фамилии отчество к субъекту не относит", () => {
    const text =
      "Керимов выступил на заседании. " +
      "Много лет спустя об этом вспоминал совершенно посторонний Иванов Пётр Сергеевич.";
    expect(conflictingPatronymics(text, KERIMOV)).toEqual([]);
  });
});

describe("обрубки слов отчествами не считаются", () => {
  /**
   * Разбор живого прогона: из 41 материала, отклонённого как «про другое
   * лицо», 30 отклонены по обрубкам собственного отчества субъекта —
   * «идович», «бусаидович», «саидович», «дович», «аидович». Среди
   * потерянного была статья о самом субъекте в Википедии.
   */
  it("длинное собственное отчество не превращается в чужое", () => {
    const text =
      "Керимов, Сулейман Абусаидович — Википедия. " +
      "Сулейман Абусаидович Керимов (род. 12 марта 1966, Дербент) — российский " +
      "предприниматель и политик, сенатор Российской Федерации от Дагестана.";
    expect(conflictingPatronymics(text, KERIMOV)).toEqual([]);
    expect(hasPatronymicConflict(text, KERIMOV)).toBe(false);
  });

  it("отчество, попавшее ровно на границу окна, читается целиком", () => {
    // Расстояние подобрано так, чтобы граница окна соседства (40 знаков от
    // фамилии) пришлась внутрь слова «Абусаидович»: обрубок «идович» — ровно
    // тот, что отклонил статью о субъекте на живом прогоне.
    const text = `Сулейман Абусаидович${"·".repeat(34)}Керимов`;
    expect(conflictingPatronymics(text, KERIMOV)).toEqual([]);
  });

  it("обрубок на краю окна соседства не выдумывается", () => {
    // Фамилия в самом начале, отчество — за границей окна в 40 знаков.
    const text = `Керимов ${"и".repeat(60)} Абусаидович`;
    expect(conflictingPatronymics(text, KERIMOV)).toEqual([]);
  });
});

describe("обычные слова на «-ич»", () => {
  it("не объявляют материал чужим", () => {
    for (const word of ["москвич", "кулич", "паралич", "экономический"]) {
      expect(conflictingPatronymics(`Керимов и ${word} в одном тексте`, KERIMOV)).toEqual([]);
    }
  });

  it("но настоящее короткое отчество в тройке с именем субъекта — конфликт", () => {
    expect(conflictingPatronymics("Керимов Сулейман Ильич подписал документ", KERIMOV)).toEqual([
      "ильич",
    ]);
  });

  it("чужое имя рядом с чужим отчеством конфликтом по отчеству не считается", () => {
    // «Керимов Пётр Ильич» — однофамилец с другим именем. Это не спор об
    // отчестве субъекта, и решает такой случай проверка имени, а не этот модуль:
    // имени субъекта в тексте нет, значит нет и `SUBJECT_MATCH`.
    expect(conflictingPatronymics("Керимов Пётр Ильич подписал документ", KERIMOV)).toEqual([]);
  });
});

describe("границы применимости", () => {
  it("без собственного отчества модуль молчит", () => {
    expect(
      conflictingPatronymics("Керимов Сулейман Абусаидович", { lastName: "Керимов", patronymics: [] })
    ).toEqual([]);
  });

  it("без фамилии в тексте сравнивать не с чем", () => {
    expect(conflictingPatronymics("Пётр Сергеевич выступил на форуме", KERIMOV)).toEqual([]);
  });
});

describe("биография субъекта не становится материалом о другом лице", () => {
  /**
   * Прогон 14.08: 27 материалов помечены «о другом лице» с уверенностью 0,9, и
   * среди них — статья РУВИКИ о самом субъекте. Причина одна: энциклопедическая
   * биография называет родню по имени-отчеству, а правило смотрело только на
   * близость к фамилии. Тексты ниже — дословно из журнала того прогона.
   */
  const texts = [
    "(Тимур Юнусов) «Timati» Тимати биография, фото, ... Тимур Юнусов родился 15 августа 1983 года в Москве. Отец — бизнесмен Ильдар Вахитович Юнусов. Мать — Симона Юнусова, в девичестве Червоморская, посвятила себя ...",
    "Тимати (Тимур Юнусов) : фото, биография ... Тимур Юнусов, известный под именем Тимати, родился летом 1983 года в Москве. Отец Тимати — Ильдар Юнусов, крупный бизнесмен, мать — Симона Яковлевна, в ...",
    "Тимати, биография и музыкальное творчество — РУВИКИ. Дед Тимати — Вахит Закирович Юнусов — родился в селе Исергапово, в Татарстане.",
    "Тимати показал первое фото с дочерью. «Юнусова Эмма Тимуровна», — написал артист.",
  ];

  it("отчества родителей, деда и дочери конфликтом не считаются", () => {
    for (const t of texts) {
      expect(conflictingPatronymics(t, YUNUSOV), t.slice(0, 60)).toEqual([]);
    }
  });

  it("чужое отчество при имени субъекта по-прежнему ловится", () => {
    expect(
      conflictingPatronymics("ИП Юнусов Тимур Ахметович — ОГРНИП: 3247746007", YUNUSOV)
    ).toEqual(["ахметович"]);
  });

  it("падежная форма имени субъекта тоже узнаётся", () => {
    expect(
      conflictingPatronymics("Дело Юнусова Тимура Ахметовича рассмотрено судом", YUNUSOV)
    ).toEqual(["ахметович"]);
  });

  it("украинское написание отчества — тот же субъект", () => {
    // Страница украинского реестра: «Тимур Ільдарович ЮНУСОВ». Буква «і»
    // делала отчество чужим, и материал уходил из аудита — при том, что он из
    // тех, ради которых аудит и заказывают.
    expect(
      conflictingPatronymics(
        "Тимур Ільдарович ЮНУСОВ Timur Ildarovich YUNUSOV. Description. Singer and entrepreneur.",
        YUNUSOV
      )
    ).toEqual([]);
  });

  it("настоящий однофамилец с тем же именем остаётся чужим", () => {
    expect(
      conflictingPatronymics(
        "Юнусов Тимур Джамальевич - Спортивный тренер в Москве. Тренерский опыт с 1997 года.",
        YUNUSOV
      )
    ).toEqual(["джамальевич"]);
  });

  it("без имён субъекта модуль молчит, а не гадает", () => {
    expect(
      conflictingPatronymics("ИП Юнусов Тимур Ахметович", {
        lastName: "Юнусов",
        patronymics: ["Ильдарович"],
      })
    ).toEqual([]);
  });
});
