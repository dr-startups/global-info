/**
 * Ввод к цитатам остаётся вводом: двоеточие — часть фразы.
 *
 * Разбор претензии вытаскивает ярлык темы из «Ярлык: текст» и двоеточие
 * снимает — для ярлыка это верно, для ввода к цитатам нет: «Найдены материалы
 * делового и биографического профиля» упирается прямо в цитату, без знака.
 * Пока цитат было две, перекладка буллета собирала его заново и двоеточие
 * возвращала; с одной цитатой она этого не делает, и лист печатал фразу без
 * знака препинания.
 */

import { describe, expect, it } from "vitest";
import { structureThemeClaimText } from "@/modules/digital-profile/orion-golden/deck-sections/fragment-builders/shared";

const QUOTE =
  "«Anders Holmström, CEO of Nordkap Capital AB — fintech investor profile» — источник (finansbladet.se/x)";
const SCALE = "Всего по теме: 3 материала, с негативным контекстом — 1.";

describe("двоеточие ввода к цитатам", () => {
  it("сохраняется при одной цитате", () => {
    const out = structureThemeClaimText(
      ["Найдены материалы делового и биографического профиля:", QUOTE, SCALE].join("\n")
    );
    expect(out.split("\n")[0]).toBe("Найдены материалы делового и биографического профиля:");
  });

  it("сохраняется и при двух цитатах", () => {
    const out = structureThemeClaimText(
      [
        "Найдены материалы делового и биографического профиля:",
        QUOTE,
        "«Контекст: другой заголовок про того же предпринимателя» — источник (svenskt.se/y)",
        SCALE,
      ].join("\n")
    );
    expect(out.split("\n")[0]).toBe("Найдены материалы делового и биографического профиля:");
  });

  it("ярлык темы двоеточия не получает", () => {
    // «Ярлык: текст» — это подпись, а не ввод к цитатам: он печатается
    // заголовком строки, и двоеточие там лишнее.
    const out = structureThemeClaimText(
      "Криминальные и судебные материалы: 7 свидетельств в источниках audit-it.ru."
    );
    expect(out.split("\n")[0]).toBe("Криминальные и судебные материалы");
  });
});
