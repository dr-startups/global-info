/**
 * Цитата чистится от знаков ударения и пробелов перед знаками; двойники по
 * тексту не печатаются (шаг 0109).
 *
 * Итоговые отчёты 18.09.2026: в цитатах Википедии печатались комбинируемые
 * знаки ударения («Серге́евич Бондарчу́к», «Дерипа́ска»), из разметки источников
 * оставались пробелы перед знаками («( род. 2 января 1968 , Дзержинск )»), а
 * резюме печатало подряд две одинаковые цитаты с зеркальных страниц cyclowiki.
 *
 * Один составитель цитаты — `quoteBody`: через него идут все производители.
 */

import { describe, expect, it } from "vitest";
import {
  dedupeQuotesByText,
  quoteBody,
  sourceQuote,
} from "@/modules/digital-profile/orion-golden/client/client-quote";

describe("цитата чистится от ударений и пробелов перед знаками", () => {
  it("Ц1: комбинируемые знаки ударения снимаются, буквы остаются", () => {
    expect(quoteBody("Фёдор Серге́евич Бондарчу́к (род. 9 мая 1967)")).toBe(
      "Фёдор Сергеевич Бондарчук (род. 9 мая 1967)"
    );
    expect(quoteBody("Оле́г Влади́мирович Дерипа́ска")).toBe("Олег Владимирович Дерипаска");
  });

  it("Ц2: пробел перед знаком и после открывающей скобки — артефакт разметки, снимается; «…» и « — » на месте", () => {
    expect(
      quoteBody("Олег Дерипаска ( род. 2 января 1968 , Дзержинск ) — российский предприниматель , миллиардер")
    ).toBe("Олег Дерипаска (род. 2 января 1968, Дзержинск) — российский предприниматель, миллиардер");
    expect(quoteBody("Валентина Матвиенко (дев. фамилия Тютина ; род. 7 апреля 1949 ) — деятель")).toBe(
      "Валентина Матвиенко (дев. фамилия Тютина; род. 7 апреля 1949) — деятель"
    );
    expect(quoteBody("Дата рождения : 09.05.1967 . Место рождения : Москва")).toBe(
      "Дата рождения: 09.05.1967. Место рождения: Москва"
    );
    expect(quoteBody("Заголовок источника ...")).toBe("Заголовок источника…");
    expect(quoteBody("Глинка Сергей … в реестре — источник")).toBe("Глинка Сергей … в реестре — источник");
  });

  it("Ц3: sourceQuote печатает уже чистый текст", () => {
    expect(sourceQuote("Серге́евич ( род. 1967 )", " — источник (x.ru)")).toBe(
      "«Сергеевич (род. 1967)» — источник (x.ru)"
    );
  });

  it("Ц4: двойники по тексту — одна цитата, разные тексты — обе", () => {
    const same = [
      { text: "Олег Владимирович Дерипаска — российский предприниматель.", url: "https://cyclowiki.org/wiki/Олег_Владимирович_Дерипаска" },
      { text: "Олег Владимирович Дерипаска — российский предприниматель.", url: "https://cyclowiki.org/wiki/Дерипаска,_Олег_Владимирович" },
      { text: "Родился 2 января 1968 года в Дзержинске.", url: "https://brobank.ru/oleg-deripaska" },
    ];
    expect(dedupeQuotesByText(same).map((q) => q.url)).toEqual([
      "https://cyclowiki.org/wiki/Олег_Владимирович_Дерипаска",
      "https://brobank.ru/oleg-deripaska",
    ]);
    // Различие только в регистре, кавычках или ударении — тот же текст.
    const near = [
      { text: "«Дерипа́ска — предприниматель»", url: "a" },
      { text: "дерипаска — предприниматель", url: "b" },
    ];
    expect(dedupeQuotesByText(near)).toHaveLength(1);
  });
});

describe("пробелы внутри кавычек источника (шаг 0115)", () => {
  it("Ц5: «« Единая Россия »» печатается без пробелов у кавычек", () => {
    const body = quoteBody("Член Высшего совета политической партии « Единая Россия » в 2009—2021 годах.");
    expect(body).toContain("„Единая Россия“");
    expect(body).not.toMatch(/„\s|\s“/u);
  });
});

describe("потерянные пробелы восстанавливаются и в цитате (шаг 0117)", () => {
  it("Ц6: «9мая 1967года» → «9 мая 1967 года», «Бондарчук—советский» → с пробелами", () => {
    expect(quoteBody("Родился 9мая 1967года в Москве")).toBe("Родился 9 мая 1967 года в Москве");
    expect(quoteBody("Бондарчук—советский актёр, в 2009—2021 годах")).toBe(
      "Бондарчук — советский актёр, в 2009—2021 годах"
    );
  });

  /**
   * Порядковое с потерянным пробелом (шаг 0126).
   *
   * Стр. 37–38 отчёта Абрамовича 20.09.2026: «В конце 1980-хгодов занимался
   * малым бизнесом», «в середине 1990-хгодов познакомился с Борисом
   * Березовским». Склейка приезжает из ответа Алисы через Arsenkin: правило
   * «цифра + две русские буквы» её не ловит, между цифрой и словом стоит
   * дефис с суффиксом.
   */
  it("Ц7: «1990-хгодов» → «1990-х годов», а «2-годичный» и «5-минутный» не трогаются", () => {
    expect(quoteBody("В конце 1980-хгодов занимался малым бизнесом")).toBe(
      "В конце 1980-х годов занимался малым бизнесом"
    );
    expect(quoteBody("В середине 1990-хгодов познакомился с Березовским")).toBe(
      "В середине 1990-х годов познакомился с Березовским"
    );
    expect(quoteBody("Прошёл 2-годичный курс и 5-минутный тест")).toBe(
      "Прошёл 2-годичный курс и 5-минутный тест"
    );
  });

  /**
   * Остальные формы потерянного пробела из того же ответа Алисы (шаг 0128).
   *
   * Стр. 43 и 45 отчёта Мордашова 20.09.2026: «В рейтинге Forbes2026 года
   * занял первое место», «состоянием около$37 млрд», «латвийским Крестом
   * Признания IIIстепени». Правило порядкового шага 0126 сюда не достаёт:
   * слева стоит слово, римская цифра или предлог.
   */
  it("Ц8: «Forbes2026», «около$37» и «IIIстепени» получают пробел", () => {
    expect(quoteBody("В рейтинге Forbes2026 года занял первое место")).toBe(
      "В рейтинге Forbes 2026 года занял первое место"
    );
    expect(quoteBody("Состояние около$37 млрд по оценке издания")).toBe(
      "Состояние около $37 млрд по оценке издания"
    );
    expect(quoteBody("Награждён Крестом Признания IIIстепени в 2013 году")).toBe(
      "Награждён Крестом Признания III степени в 2013 году"
    );
    // Не трогаются: идентификатор без года и число, которое не год.
    expect(quoteBody("Код afNUb1014 присвоен записи реестра")).toBe(
      "Код afNUb1014 присвоен записи реестра"
    );
  });
});
