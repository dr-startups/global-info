/**
 * Цитата — не почтовый адрес, не кредит фотографа, а примеры различимы (шаг 0130).
 *
 * Отчёт Мордашова 20.09.2026:
 *   * стр. 70 — под темой «Внимание по линии безопасности / оборонный контур»
 *     напечатано «А. Офис в Санкт-Петербурге: 192012, Россия, г. Санкт-
 *     Петербург, пр. Обуховской Обороны, д. 112, к. 2, лит.» (alestech.ru).
 *     Это выгрузка контактов, и обрывается она на «лит.»;
 *   * стр. 15 — «Фото: RuNews24 На ПМЭФ-2026 владелец „Северстали“ Алексей
 *     Мордашов заявил о сокращении инвестиционной программы…»: подпись к
 *     фотографии приклеена к началу фразы;
 *   * стр. 51 — «(примеры: Alexey Alexandrovits Mordaschov · Alexey
 *     Aleksandrovich MORDASHOV · Alexey Alexandrovits Mordaschov)»: первый и
 *     третий совпадают дословно. Стр. 18 — «(примеры: Мордашов, Алексей)»:
 *     голое имя вместо материала.
 *
 * Кредит не отрезается, а закрывает цитату целиком: где кончается подпись и
 * начинается фраза, снаружи не видно («Фото: Алексей Мордашов На фоне завода»
 * режется в другом месте, чем «Фото: RuNews24 На ПМЭФ-2026»). У страницы есть
 * другие предложения, и правило то же, что у обрывка: целое или ничего.
 */

import { describe, expect, it } from "vitest";
import { looksLikeWholeStatement } from "@/modules/digital-profile/orion-golden/analytics/theme-quote";
import { distinctExampleTitles } from "@/modules/digital-profile/orion-golden/analytics/finding-synthesizer";

const ADDRESS_DUMP =
  "А. Офис в Санкт-Петербурге: 192012, Россия, г. Санкт-Петербург, пр. Обуховской Обороны, д. 112, к. 2, лит.";

const PHOTO_CREDIT =
  "Фото: RuNews24 На ПМЭФ-2026 владелец „Северстали“ Алексей Мордашов заявил о сокращении " +
  "инвестиционной программы на 24%.";

describe("выгрузка контактов цитатой не бывает", () => {
  it("В1: почтовый адрес с индексом и сокращениями — не фраза", () => {
    expect(looksLikeWholeStatement(ADDRESS_DUMP)).toBe(false);
  });

  it("В2: обычное предложение с адресом внутри остаётся фразой", () => {
    expect(
      looksLikeWholeStatement(
        "Головной офис компании находится в Череповце на Мира, и там же работает совет директоров."
      )
    ).toBe(true);
  });
});

describe("кредит фотографа закрывает цитату целиком", () => {
  it("В3: фраза, начатая подписью к фото, цитатой не становится", () => {
    expect(looksLikeWholeStatement(PHOTO_CREDIT)).toBe(false);
    expect(looksLikeWholeStatement("Фото: Алексей Мордашов На фоне завода в Череповце")).toBe(false);
  });

  it("В4: слово «фото» в середине фразы её не трогает", () => {
    expect(
      looksLikeWholeStatement("На фото с ПМЭФ Мордашов стоит рядом с главой правительства.")
    ).toBe(true);
  });
});

describe("примеры материалов различимы", () => {
  it("В5: повтор снимается, голое имя примером не бывает", () => {
    const out = distinctExampleTitles([
      "Alexey Alexandrovits Mordaschov",
      "Alexey Aleksandrovich MORDASHOV",
      "Alexey Alexandrovits Mordaschov",
      "США ввели санкции против «Северстали» и её владельца",
    ]);
    expect(out).toEqual(["США ввели санкции против «Северстали» и её владельца"]);
  });

  it("В6: разные содержательные заголовки остаются оба", () => {
    const out = distinctExampleTitles([
      "США ввели санкции против «Северстали» и её владельца",
      "Суд ЕС отклонил иск Мордашова против санкций",
    ]);
    expect(out).toHaveLength(2);
  });
});
