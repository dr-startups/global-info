/**
 * Сюжет прочитанных страниц цитирует основание вывода, а не лид (шаг 0118).
 *
 * Стр. 4 отчёта Бондарчука 19.09.2026, «Личная жизнь, разводы и семейные
 * события»: «Федор Сергеевич Бондарчук — российский кинорежиссер, актер и
 * продюсер фильмов. … Родился 9 мая 1967 года в Москве» (lenta.ru) — первая
 * цитата страницы, фрагмент принадлежности. Правило то же, что у основания
 * рамки на снимке выдачи: слово негатива → не лид → первая.
 */

import { describe, expect, it } from "vitest";
import { readPlotQuote } from "@/modules/digital-profile/orion-golden/analytics/client-summary-pack-builder";

const LEAD =
  "Федор Сергеевич Бондарчук — российский кинорежиссер, актер и продюсер фильмов. Председатель совета директоров кинокомпании «Ленфильм». Родился 9 мая 1967 года в Москве";
const PARTY = "Член Высшего совета политической партии «Единая Россия» в 2009—2021 годах.";
const SCHOOL =
  "Не отличался успешной учёбой и хорошим поведением, в школьные годы стал пить, курить и хулиганить";
const COURT = "Суд Москвы арестовал имущество режиссёра по иску кредиторов на 40 млн рублей.";

describe("цитата сюжета прочитанных страниц", () => {
  it("С1: из [лид, партия, хулиганство] берётся не лид", () => {
    const q = readPlotQuote([{ text: LEAD }, { text: PARTY }, { text: SCHOOL }]);
    expect(q).toContain("Единая Россия");
    expect(q).not.toContain("Родился 9 мая");
  });

  it("С2: фраза со словом негатива идёт первой, даже если стоит после лида", () => {
    const q = readPlotQuote([{ text: LEAD }, { text: COURT }]);
    expect(q).toContain("арестовал имущество");
  });

  it("С3: без цитат — пусто", () => {
    expect(readPlotQuote([])).toBe("");
  });
});
