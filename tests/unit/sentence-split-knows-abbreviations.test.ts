/**
 * Токенизатор предложений знает сокращения, инициалы и скобки (шаг 0110).
 *
 * Отчёт Дерипаски на v200 (18.09.2026): боковая панель печатала цитату
 * «Оле́г Влади́мирович Дерипа́ска ( род.», а блок темы — «2 января 1968,
 * Дзержинск …) — российский предприниматель…» дважды. Оба — обрывки одного
 * предложения Википедии: `splitSentences` резал по «род.», как по концу
 * предложения. Тот же нож режет «г. Москва», «Ф. С. Бондарчук», «12 тыс. рублей».
 */

import { describe, expect, it } from "vitest";
import { splitSentences } from "@/modules/digital-profile/orion-golden/deck-sections/sentence-split";

describe("граница предложения — не внутри скобки, не после сокращения и не после инициала", () => {
  it("С1: «(род. 2 января 1968, Дзержинск)» остаётся внутри предложения", () => {
    expect(
      splitSentences("Олег Дерипаска (род. 2 января 1968, Дзержинск) — предприниматель. Родители с Кубани.")
    ).toEqual(["Олег Дерипаска (род. 2 января 1968, Дзержинск) — предприниматель.", "Родители с Кубани."]);
    expect(splitSentences("Матвиенко (дев. фамилия Тютина; род. 7 апреля 1949) — деятель. Далее.")).toEqual([
      "Матвиенко (дев. фамилия Тютина; род. 7 апреля 1949) — деятель.",
      "Далее.",
    ]);
  });

  it("С2: сокращения «г.», «тыс.», «им.», «ул.» не кончают предложение", () => {
    expect(splitSentences("Родился в г. Дзержинске. Учился в МГТУ.")).toEqual([
      "Родился в г. Дзержинске.",
      "Учился в МГТУ.",
    ]);
    expect(splitSentences("Заплатил 12 тыс. рублей. Ушёл.")).toEqual(["Заплатил 12 тыс. рублей.", "Ушёл."]);
    expect(splitSentences("Гимназия им. Капцовых на ул. Ленина. Открыта в 1990 г. Работает.")).toEqual([
      "Гимназия им. Капцовых на ул. Ленина.",
      "Открыта в 1990 г. Работает.",
    ]);
  });

  it("С3: инициалы не кончают предложение", () => {
    expect(splitSentences("Режиссёр Бондарчук Ф. С. снял фильм. Премьера в мае.")).toEqual([
      "Режиссёр Бондарчук Ф. С. снял фильм.",
      "Премьера в мае.",
    ]);
    expect(splitSentences("Матвиенко В. И. — спикер. Избрана в 2011 году.")).toEqual([
      "Матвиенко В. И. — спикер.",
      "Избрана в 2011 году.",
    ]);
  });

  it("С4: прежние границы на месте — точка, «!», «?», «…» вне скобок и кавычек делят", () => {
    expect(splitSentences("Первое. Второе! Третье? Четвёртое… Пятое.")).toEqual([
      "Первое.",
      "Второе!",
      "Третье?",
      "Четвёртое…",
      "Пятое.",
    ]);
    expect(splitSentences("Он сказал: «Всё. Хватит». Ушёл.")).toEqual(["Он сказал: «Всё. Хватит».", "Ушёл."]);
  });

  it("С5: непарная скобка правило скобок снимает — текст не склеивается в одно предложение", () => {
    expect(splitSentences("Скобка (открыта и не закрыта. Второе предложение.")).toEqual([
      "Скобка (открыта и не закрыта.",
      "Второе предложение.",
    ]);
  });
});
