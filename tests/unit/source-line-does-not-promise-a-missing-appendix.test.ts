/**
 * Строка происхождения не отправляет читателя в приложение.
 *
 * Запасная ветка печатала «Источники — поисковая выдача; полный перечень в
 * приложении» на каждой странице, у которой нет собственных доменов: девять
 * слайдов прогона 92, восемь — эталона-72, девять — золотого кейса. Приложения
 * в деке прогона 92 нет вовсе (все семь находок `SUBJECT_MATCH`, фрагмент
 * отброшен как `EMPTY_VALID_OMITTED`), а там, где оно есть, оно перечисляет
 * материалы, требующие идентификации, — перечнем источников не является ни на
 * одном прогоне. Поэтому обещание снято **безусловно**, а не по признаку
 * «есть ли приложение в деке».
 *
 * Вторая половина правки — страница, которая не показала ничего: приписывать
 * источники нечему, и подвала у неё нет вовсе.
 */

import { describe, expect, it } from "vitest";
import {
  pageSourceLine,
  sourcesSentence,
  type PageEvidenceView,
} from "@/modules/digital-profile/orion-golden/deck-sections/fragment-builders/shared";

function view(refs: string[], domains: string[]): PageEvidenceView {
  return {
    refs,
    domains,
    findings: [],
    supportDomains: new Map(),
    supportRows: new Map(),
  };
}

describe("страница без собственных адресов", () => {
  it("называет источником саму выдачу и говорит, почему адресов нет", () => {
    const line = pageSourceLine(view(["inventory:s1", "inventory:s2"], []));
    expect(line).toBe("Источник — поисковая выдача: у показанных элементов нет отдельных адресов.");
  });

  it("не отправляет читателя в раздел ни в какой форме слова", () => {
    expect(pageSourceLine(view(["inventory:s1"], []))).not.toMatch(/приложени/iu);
    expect(sourcesSentence([])).not.toMatch(/приложени/iu);
  });

  it("одна ссылка без домена — это всё-таки показанный элемент", () => {
    // `p31_uae_knowledge` прогона 92: одна ссылка, ноль доменов. Подвал у такой
    // страницы есть — объяснять нечему только той, что не показала ничего.
    expect(pageSourceLine(view(["inventory:s1"], []))).not.toBe("");
  });
});

describe("страница, которая ничего не показала", () => {
  it("подвала источников не печатает вовсе", () => {
    // Стр. 44 прогона 92: `knowledgeBlocks: 0`, ноль ссылок, ноль доменов.
    // Причину пустоты называет тело страницы, а не строка происхождения.
    expect(pageSourceLine(view([], []))).toBe("");
  });
});

describe("названные площадки печатаются по-прежнему", () => {
  it("подвал не исчезает из-за пустого списка ссылок", () => {
    // Ссылок у вида может не быть, а домены прийти находкой страницы: правило
    // пустого подвала спрашивает про **оба** признака, иначе оно снимает
    // законный подвал.
    expect(pageSourceLine(view([], ["tass.ru"]))).toBe("Источники — tass.ru.");
  });

  it("страница со своими доменами называет их", () => {
    expect(pageSourceLine(view(["inventory:s1"], ["tass.ru", "ria.ru"]))).toBe(
      "Источники — tass.ru и ria.ru."
    );
  });
});

/**
 * «Адресов нет» и «адреса есть, назвать нельзя» — разные состояния.
 *
 * Обе ветки судят по `clientSafeDomains`, а он выбрасывает демо- и мок-домены
 * (`composite-serp-merge.ts`). Страница, у которой все площадки отфильтрованы,
 * печатала «у показанных элементов нет отдельных адресов» — утверждение о
 * данных при условии о допустимости печати. Фраза о собственных адресах
 * остаётся у тех, у кого адресов нет: подсказки, связанные запросы, блоки
 * панели.
 */
describe("адреса есть, но назвать их нельзя", () => {
  it("не утверждает, что адресов у элементов нет", () => {
    const line = pageSourceLine(view(["inventory:s1"], ["news.example.org"]));
    expect(line).toBe("Источник — поисковая выдача.");
  });

  it("подвал при этом не исчезает", () => {
    expect(sourcesSentence(["news.example.org"])).not.toBe("");
  });
});
