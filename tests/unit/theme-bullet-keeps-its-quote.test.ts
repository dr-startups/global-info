/**
 * Обещание цитаты живёт вместе с цитатой.
 *
 * Стр. 12 отчёта 85: «Найдены публикации о финансовых претензиях и долговых
 * спорах:.» — и пустой лист. Подгонка блока по бюджету сбрасывает целые строки
 * с конца и унесла **единственную** цитату, оставив рамку, которая её обещает.
 * Двоеточие с точкой на пустой странице читается как сбой программы, а не как
 * отчёт, за который заплачено.
 *
 * Цитата длинная не потому, что мы её выдумали: это предложение прочитанной
 * страницы плюс полный адрес источника. Ужать её внутри кавычек можно, выкинуть
 * — нет: без неё блок ничего не утверждает.
 */

import { describe, expect, it } from "vitest";
import { fitStructuredBullet } from "@/modules/digital-profile/orion-golden/deck-sections/fragment-builders/shared";

const BLOCK = [
  "«Финансовые претензии / долговые споры»",
  "Найдены публикации о финансовых претензиях и долговых спорах:",
  "«В суде Алексея Евгеньевича Егорова источники финансирования не проверяют, неизвестные" +
    " лица платят миллионы, а грязные деньги превращаются в чистую недвижимость. Главный" +
    " вопрос: кто и почему этому помогает?» — источник" +
    " (pravda-mn.com/novosti/item/1145789-arbitrazhnyy-sud-krasnodara-kak-prachechnaya-kak-" +
    "predsedatel-aleksey-evgenevich-egorov-pomogaet-kriminalu-otmyvat-milliardy-cherez-bankrotstva)",
  "Где видно: pravda-mn.com.",
  "Банки и инвесторы обычно запрашивают статус обязательств и судебные справки.",
  "Всего по теме: 1 материал.",
].join("\n");

describe("блок темы не обещает цитату, которой не печатает", () => {
  it("бюджет мал — цитата ужимается, а не исчезает", () => {
    const out = fitStructuredBullet(BLOCK, 520);
    expect(out.length).toBeLessThanOrEqual(520);
    expect(out).toContain("источники финансирования не проверяют");
    expect(out).toContain("pravda-mn.com");
  });

  it("под тесным бюджетом цитата всё равно остаётся — она и есть блок", () => {
    // Сброс целых строк с конца дошёл бы и до неё: цитата стоит последней,
    // когда служебные строки уже сброшены. Здесь и держится правка.
    for (const budget of [400, 300, 200]) {
      const out = fitStructuredBullet(BLOCK, budget);
      expect(out.length, `бюджет ${budget}`).toBeLessThanOrEqual(budget);
      // Слова самой цитаты, а не любые кавычки: ярлык темы тоже стоит в
      // «ёлочках», и проверка по ним прошла бы на пустом блоке.
      expect(out, `бюджет ${budget}: ${out}`).toContain("источники финансирования");
    }
  });

  it("ни при каком бюджете блок не кончается двоеточием", () => {
    for (const budget of [520, 300, 200, 140, 90, 60]) {
      const out = fitStructuredBullet(BLOCK, budget);
      expect(out.replace(/\s+$/u, "").endsWith(":"), `бюджет ${budget}: ${out}`).toBe(false);
      expect(out).not.toContain(":.");
    }
  });

  it("помещающийся блок не трогается", () => {
    expect(fitStructuredBullet(BLOCK, 2000)).toBe(BLOCK);
  });
});
