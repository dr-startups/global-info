/**
 * Число называет свой охват (шаг 0133).
 *
 * Отчёт Мордашова 20.09.2026. Стр. 9, матрица: «Корпоративное владение. Всего
 * по теме: 39 материалов, с негативным контекстом — 11.» Стр. 15, страница
 * России: «„Корпоративное владение“ … Всего по теме: 31 материал, с
 * негативным контекстом — 11.» Числа разные, тема одна, фраза одинаковая, и
 * охват не назван нигде.
 *
 * Оба числа верны: матрица считает по всему отчёту, региональная страница — по
 * своему региону. Форма предложения остаётся одной — соседние листы, которые
 * называют одно двумя разными фразами, читаются как разные сущности, — а охват
 * встаёт рядом с числом.
 */

import { describe, expect, it } from "vitest";
import { themeScaleLine } from "@/modules/digital-profile/orion-golden/analytics/finding-synthesizer";

describe("строка счёта темы", () => {
  it("Н1: охват отчёта назван", () => {
    expect(themeScaleLine(39, 11, "по отчёту")).toBe(
      "Всего по теме: 39 материалов по отчёту, с негативным контекстом — 11."
    );
  });

  it("Н2: охват региона назван", () => {
    expect(themeScaleLine(31, 11, "по России")).toBe(
      "Всего по теме: 31 материал по России, с негативным контекстом — 11."
    );
  });

  it("Н3: без негатива форма та же", () => {
    expect(themeScaleLine(4, 0, "по отчёту")).toBe("Всего по теме: 4 материала по отчёту.");
  });

  it("Н4: охват не назван — строка прежняя, старые артефакты не ломаются", () => {
    expect(themeScaleLine(4, 0)).toBe("Всего по теме: 4 материала.");
  });

  it("Н5: признак строки счёта по-прежнему её узнаёт", () => {
    expect(/^(Всего по теме|В корпусе):/u.test(themeScaleLine(39, 11, "по отчёту"))).toBe(true);
  });
});
